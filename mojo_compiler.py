def _synthesize_fieldwise_inits(stmts: list) -> list:
    """Mojo's @fieldwise_init decorator synthesizes a memberwise
    __init__(out self, field1, field2, ...) constructor alongside any
    explicit __init__ a struct already defines. The parser only sees Mojo
    source text and has no other way to represent this real, additional
    constructor overload, so materialize it here as an ordinary
    FunctionDef appended to StructDef.methods.

    Called once, unconditionally, at the end of parse_module() — not as an
    opt-in step some callers remember to invoke — so every consumer of a
    parsed module (codegen's own struct-method walk, source-based overload
    elaboration, dylib reflection export) sees the identical
    StructDef.methods list. If different consumers synthesized this
    independently, a dylib-resolved call and a source-elaborated call for
    the same struct could disagree on the overload's parameter order/mangling.

    Idempotent via a marker on the StructDef itself (not a local set),
    since parsed stmts get cached and handed to multiple GimpleGen
    instances (module_stmts) — a second call on the same objects must not
    double-append.
    """
    for s in stmts:
        if not isinstance(s, StructDef):
            continue
        if getattr(s, '_fieldwise_ctor_synthesized', False):
            continue
        s._fieldwise_ctor_synthesized = True
        decs = s.decorators or []
        if 'fieldwise_init' not in decs and 'value' not in decs:
            continue
        field_decls = [f for f in s.fields if isinstance(f, VarDecl)]
        if not field_decls:
            continue
        existing = {m.name for m in s.methods}
        # A struct can hand-write its own __init__ (e.g. a no-arg one for
        # Defaultable conformance) alongside @fieldwise_init's synthesized
        # memberwise one — real Mojo overloads on arity, it doesn't let the
        # hand-written one suppress the synthesized one. Comparing by name
        # alone (as opposed to (name, arity)) treated any hand-written
        # __init__ as "already have one" and dropped the fieldwise overload
        # entirely, so `Person("John Smith", 42)` had no matching __init__
        # to call even though the struct is @fieldwise_init.
        target_arity = 1 + len(field_decls)  # self + one param per field
        has_matching_init = any(
            m.name == '__init__' and len(m.params) == target_arity
            for m in s.methods)
        if not has_matching_init:
            params = [('self', s.name)] + [(f.name, f.type_ann) for f in field_decls]
            body = [AssignStmt(target=MemberExpr(obj=IdentExpr(name='self'), member=f.name),
                                value=IdentExpr(name=f.name))
                    for f in field_decls]
            s.methods.append(FunctionDef(
                name='__init__', params=params, return_type=None, body=body,
                param_convs={'self': 'out'}))
        if 'value' not in decs:
            continue
        # @value additionally synthesizes __copyinit__/__moveinit__ — a
        # member-by-member copy of `existing` into `self` (this interpreter
        # has no distinct move-vs-copy semantics, so both bodies match).
        if '__copyinit__' not in existing:
            params = [('self', s.name), ('existing', s.name)]
            body = [AssignStmt(target=MemberExpr(obj=IdentExpr(name='self'), member=f.name),
                                value=MemberExpr(obj=IdentExpr(name='existing'), member=f.name))
                    for f in field_decls]
            s.methods.append(FunctionDef(
                name='__copyinit__', params=params, return_type=None, body=body,
                param_convs={'self': 'out'}))
        if '__moveinit__' not in existing:
            params = [('self', s.name), ('existing', s.name)]
            body = [AssignStmt(target=MemberExpr(obj=IdentExpr(name='self'), member=f.name),
                                value=MemberExpr(obj=IdentExpr(name='existing'), member=f.name))
                    for f in field_decls]
            s.methods.append(FunctionDef(
                name='__moveinit__', params=params, return_type=None, body=body,
                param_convs={'self': 'out', 'existing': 'owned'}))
    return stmts

# Built-in stdlib trait names — never declared via `trait X:` in the
# source being parsed, so Parser._known_traits (a single forward pass over
# the file's own tokens) can't discover them; hardcoded instead.
_BUILTIN_TRAITS = {
    'Movable', 'Copyable', 'ImplicitlyCopyable', 'Defaultable', 'AnyType',
    'Hashable', 'Stringable', 'Sized', 'Boolable', 'Intable', 'Writable',
    'KeyElement', 'CollectionElement', 'EqualityComparable', 'Representable',
    'Comparable', 'Indexer', 'Absable', 'Powable', 'Roundable',
}

class Parser:
    def __init__(self, tokens: list[Token]):
        self._tok = tokens
        self._pos = 0
        self._filename = ""
        self._pending_decs = []  # decorators awaiting next struct/trait
        # `struct Box[T: Movable]:` — a generic TYPE parameter bound by a
        # trait, syntactically identical to `struct SIMD[width: Int]:`'s
        # genuine comptime VALUE parameter (`name: Ident` either way). This
        # parser has no type checker, so the only way to tell them apart is
        # to know whether the name after the colon is a trait; a single
        # forward scan of this file's own tokens for `trait NAME` finds every
        # user-defined trait (traits are declared before use in this dialect,
        # same assumption structs/functions already rely on), unioned with
        # the built-in stdlib traits above that never appear as a `trait`
        # declaration in user source. See _parse_struct_params_as_fields,
        # which used to add every `T: Movable` as a real VarDecl field —
        # corrupting @fieldwise_init's synthesized constructor arity for any
        # generic struct with a trait-bounded type parameter.
        self._known_traits = set(_BUILTIN_TRAITS)
        for i, t in enumerate(tokens):
            if t.kind == "KW" and t.value == "trait" and i + 1 < len(tokens):
                nxt = tokens[i + 1]
                if nxt.kind == "NAME":
                    self._known_traits.add(nxt.value)

    def with_filename(self, filename: str):
        """Attach a source filename for `file:line:col:` diagnostics.
        Kept as a separate setter (not an __init__ param) because the
        self-hosted compiled path emits one fixed C signature per function —
        callers passing 1 vs 2 constructor args would produce two conflicting
        declarations for Parser___init__."""
        self._filename = filename
        return self

    def _peek(self, offset: int = 0) -> Token:
        i = self._pos + offset
        if i < len(self._tok):
            return self._tok[i]
        last_line = 0
        last_col = 0
        if self._tok:
            last_tok = self._tok[-1]
            last_line = last_tok.line
            last_col = last_tok.col
        # Pass every field explicitly (not relying on Token's `col: int = 0`
        # dataclass default) — the self-hosted compiled path doesn't reliably
        # apply Python default field values on a constructor call that omits
        # them, so an implicit default can come back as an uninitialized/
        # None-ish slot instead of 0 (seen as "file:line:None:" in a
        # compiled-path diagnostic).
        return Token("EOF", "", line=last_line, col=last_col)

    def _advance(self) -> Token:
        t = self._tok[self._pos]
        if self._pos < len(self._tok) - 1: self._pos += 1
        return t

    def _loc(self, tok: Token) -> str:
        """Format a gcc-style `file:line:col: ` prefix for a diagnostic.
        Omits the filename segment when none was supplied to the Parser
        (e.g. inline snippets compiled from a string with no source file).

        `tok` is required (no default/None-fallback) — every call site
        already has a concrete token in hand, and a `tok if tok is not
        None else self._peek()` ternary here previously confused the
        self-hosted compiled path's type inference: the phi'd local came
        back typed int64_t instead of Token*, so `.col` silently read back
        as garbage/None in compiled diagnostics (`.line` happened to still
        work). Only ever called from *inside* an f-string interpolation at
        each raise site (never via a `raise self._error(...)` indirection)
        — the compiled path's raise-lowering (_gen_stmt_RaiseStmt) pattern-
        matches the literal shape `raise ExcName(single_string_arg)` to
        capture the exception's type tag and message; routing the raise
        through a helper method call breaks that match silently (the
        exception still fires, but with an empty message and no type tag,
        since `val.func` is a MemberExpr instead of a bare IdentExpr)."""
        if self._filename:
            return f"{self._filename}:{tok.line}:{tok.col}: "
        return f"{tok.line}:{tok.col}: "

    def _expect(self, kind: str, value: str = None) -> Token:
        t = self._peek()
        if t.kind != kind:
            raise SyntaxError(f"{self._loc(t)}Expected {kind} got {t.kind}({t.value!r})")
        if value and t.value != value:
            raise SyntaxError(f"{self._loc(t)}Expected {value!r} got {t.value!r}")
        return self._advance()

    def _ident(self) -> str:
        """Consume an identifier, allowing keywords (e.g. `out`, `mut`) and
        backtick-quoted names to be used as plain identifiers."""
        t = self._peek()
        if t.kind in ("NAME", "KW"):
            return self._advance().value
        if t.kind == "STRING" and t.value.startswith("`"):
            return self._advance().value
        raise SyntaxError(f"{self._loc(t)}Expected NAME or KW got {t.kind}({t.value!r})")

    def _parse_dotted_name(self) -> str:
        """Consume a dotted name like `asyncio.CancelledError` and return it
        as a single string. Used for exception types in `except` clauses."""
        name = self._ident()
        while self._peek().kind == "DOT":
            self._advance(); name += "." + self._ident()
        return name

    def _skip_newlines(self):
        while self._peek().kind == "NEWLINE": self._advance()

    def _at_end(self) -> bool: return self._peek().kind == "EOF"
    def _is_kw(self, *w) -> bool:
        t = self._peek(); return t.kind == "KW" and t.value in w

    def parse_module(self) -> list:
        stmts = []
        self._skip_newlines()
        while not self._at_end():
            stmts.append(self._parse_stmt())
            self._skip_newlines()
        return _synthesize_fieldwise_inits(stmts)

    def _parse_block(self) -> list:
        # Support inline single-statement body: "def foo(): return x" on one line
        if self._peek().kind != "NEWLINE":
            start_line = self._peek().line
            stmt = self._parse_stmt()
            stmts = [stmt] if stmt is not None else []
            # Same-line multi-statement inline body: "if x: a = 1; continue" —
            # the tokenizer (see py_tokenize's `_split_on_separators` loop)
            # splits each ';'-separated piece of a physical line into its own
            # token run terminated by a NEWLINE, which loses the fact that
            # every piece after the colon is still part of THIS compound
            # statement's body, not a sibling of the enclosing block. Without
            # this loop, only the first piece ("a = 1") became the body and
            # anything after the first ';' (here, "continue") silently became
            # a sibling statement instead — executing unconditionally on every
            # loop iteration regardless of `x`. Detected via physical line
            # number: every ';'-split piece from the same source line shares
            # the same `line`, so a NEWLINE followed by a token still on the
            # same line means "more of this same-line body", not a new line.
            while (self._peek().kind == "NEWLINE"
                   and self._peek(1).line == start_line
                   and self._peek(1).kind not in ("DEDENT", "EOF")):
                self._advance()  # consume the semicolon-split NEWLINE
                start_line = self._peek().line
                nxt = self._parse_stmt()
                if nxt is not None:
                    stmts.append(nxt)
            return stmts
        self._expect("NEWLINE")
        self._skip_newlines()
        # Empty block: comment-only body produces DEDENT with no INDENT
        if self._peek().kind in ("DEDENT", "EOF", "KW"):
            return [PassStmt()]
        self._expect("INDENT")
        stmts = []
        self._skip_newlines()
        while self._peek().kind not in ("DEDENT", "EOF"):
            stmts.append(self._parse_stmt())
            self._skip_newlines()
        self._expect("DEDENT")
        return stmts

    def _parse_stmt(self):
        t = self._peek()
        line, col = t.line, t.col
        # Handle "yield from expr" — yield is NAME('yield'), from is KW('from')
        if t.kind == "NAME" and t.value == "yield" and self._peek(1).kind == "KW" and self._peek(1).value == "from":
            self._advance()  # consume yield
            self._advance()  # consume from
            self._parse_expr(0)  # parse the delegated generator expression
            return ExprStmt(value=IdentExpr(name='yield'), line=line, col=col)
        # `match` is a soft keyword (like Python's own) — only a match
        # statement when followed by a real expression and a top-level `:`
        # before the line ends; otherwise it's an ordinary identifier
        # (`match(x)` a call, `match = 5` an assignment, etc).
        if t.kind == "NAME" and t.value == "match" and self._is_match_stmt():
            return self._parse_match()
        if t.kind == "KW":
            if t.value == "import": return self._parse_import()
            if t.value == "from":   return self._parse_from_import()
            if t.value == 'var':
                # "var = expr" means 'var' is used as a plain identifier (Python compat)
                # "var name" or "var name:" is a proper var declaration
                if self._peek(1).kind == "ASSIGN":
                    pass  # fall through to expression/assignment handling below
                else:
                    return self._parse_var_decl()
            if t.value == 'if': return self._parse_if()
            if t.value == 'while': return self._parse_while()
            if t.value == 'for': return self._parse_for()
            if t.value in ("def", "fn"):
                # fn(  →  variable named "fn" being called; treat as expression
                # fn =  →  variable named "fn" being assigned; treat as expression
                if t.value == "fn" and self._peek(1).kind in ("LPAREN", "ASSIGN", "AUGASSIGN", "DOT"):
                    pass  # fall through to expression statement
                else:
                    self._advance(); return self._parse_funcdef([])
            if t.value in ("struct", "class"): return self._parse_struct()
            if t.value == "trait": return self._parse_trait()
            if t.value == "try": return self._parse_try()
            if t.value == "with": return self._parse_with()
            if t.value == "comptime": return self._parse_comptime()
            if t.value == 'pass': return self._parse_pass()
            if t.value == 'return': return self._parse_return()
            if t.value == 'raise': return self._parse_raise()
            if t.value == 'break': return self._parse_break()
            if t.value == 'continue': return self._parse_continue()
            if t.value == 'assert': return self._parse_assert()
            if t.value == 'global': return self._parse_global()
        # Handle __mlir_attr and other MLIR/special forms as opaque no-ops.
        # NOT __mlir_region (handled below) and NOT __mlir_op: a bare __mlir_op
        # statement is a real side-effecting op (e.g. `pop.store`, ownership
        # markers) — let it fall through to an expression statement so the
        # backend lowers it (mlir.py).
        if t.kind == "NAME" and t.value.startswith("__mlir") \
                and t.value not in ("__mlir_region", "__mlir_op"):
            self._advance()  # skip __mlir_attr/etc
            # Skip string literal if present
            if self._peek().kind == "LPAREN":
                self._advance()  # skip (
                if self._peek().kind == "STRING":
                    self._advance()  # skip string
                self._advance()  # skip )
            # Skip the rest of the line (result type annotation, etc)
            while self._peek().kind not in ("NEWLINE", "DEDENT", "EOF"):
                self._advance()
            return PassStmt()
        # Handle __extension Type: methods and __mlir_region name(...): body
        if t.kind == "NAME" and t.value in ("__extension", "__mlir_region"):
            self._advance()  # skip __extension or __mlir_region
            name = self._expect("NAME").value
            # Skip any function call arguments if present
            if self._peek().kind == "LPAREN":
                self._advance()  # (
                depth = 1
                while depth > 0:
                    t_inner = self._advance()
                    if t_inner.kind == "LPAREN":
                        depth += 1
                    elif t_inner.kind == "RPAREN": depth -= 1
            self._expect("COLON")
            # Check if there is a body on this line or on following lines
            if self._peek().kind == "NEWLINE":
                # Indented block follows
                body = self._parse_block()
            else:
                # Body on same line, skip until newline
                while self._peek().kind not in ("NEWLINE", "DEDENT", "EOF"):
                    self._advance()
            # Treat as a pass statement
            return PassStmt(line=line, col=col)
        if t.kind == "OP" and t.value == "@":
            decs = []
            while self._peek().kind == "OP" and self._peek().value == "@":
                self._advance()
                # str(): Token.value is typed `object`, so without this the
                # self-hosted codegen infers dec_name as int64_t and the dotted
                # concat below becomes int64_t + char* (a GCC build2 ICE).
                dec_name = str(self._expect("NAME").value)
                # Dotted decorator name: @functools.lru_cache, @a.b.c
                while self._peek().kind == "DOT":
                    self._advance()  # consume '.'
                    dec_name = dec_name + "." + str(self._expect("NAME").value)
                # Handle decorator with arguments: @decorator(args)
                if self._peek().kind == "LPAREN":
                    self._advance()  # skip LPAREN
                    depth = 1
                    while depth > 0:
                        t = self._peek()
                        if t.kind == "LPAREN":
                            depth += 1
                        elif t.kind == "RPAREN": depth -= 1
                        self._advance()
                decs.append(dec_name)
                self._skip_newlines()
            kw = self._peek()
            if kw.kind == "KW" and kw.value in ("struct", "class"):
                self._pending_decs = decs
                return self._parse_struct()
            if kw.kind == "KW" and kw.value == "trait":
                self._pending_decs = decs
                return self._parse_trait()
            if kw.kind == "KW" and kw.value == "comptime":
                return self._parse_comptime()
            # Handle 'async def' — async is tokenized as NAME not KW
            if kw.kind == "NAME" and kw.value == "async":
                self._advance()
                kw = self._peek()
            if kw.kind == "KW" and kw.value in ("def", "fn"):
                self._advance()
                return self._parse_funcdef(decs)
            # Field-level decorators (e.g. @__allow_legacy_any_origin_fields)
            # applied to a `var` declaration: decorators carry no codegen
            # meaning here, so just parse the var decl and drop them.
            if kw.kind == "KW" and kw.value == "var":
                return self._parse_var_decl()
            self._expect("KW", "def or fn")
            return self._parse_funcdef(decs)
        expr = self._parse_expr(0)
        # Check for tuple unpacking in assignment (a, b = ...)
        if self._peek().kind == "COMMA":
            targets = [expr]
            while self._peek().kind == "COMMA":
                self._advance()
                if self._peek().kind == "ASSIGN": break
                targets.append(self._parse_expr(0))
            # Check if this is actually an assignment
            if self._peek().kind == "ASSIGN":
                self._advance()
                val = self._parse_expr(0)
                # Check for tuple RHS: a, b = x, y
                if self._peek().kind == "COMMA":
                    rhs_elements = [val]
                    while self._peek().kind == "COMMA":
                        self._advance()
                        if self._peek().kind in ("NEWLINE", "DEDENT", "EOF"):
                            break
                        rhs_elements.append(self._parse_expr(0))
                    val = TupleExpr(elements=rhs_elements)
                tuple_target = TupleExpr(elements=targets)
                return AssignStmt(target=tuple_target, value=val)
            # Not an assignment, treat as expression statement with comma operator
            return ExprStmt(TupleExpr(elements=targets), line=line, col=col)
        # Annotated assignment: target: Type [= value]
        if self._peek().kind == "COLON":
            self._advance()
            type_ann = self._parse_type_ann()
            if self._peek().kind == "ASSIGN":
                self._advance()
                val = self._parse_expr(0)
                # `x: Type = value` previously silently discarded the
                # annotation (AssignStmt has no type_ann field) — harmless
                # for a local (type gets re-inferred from the value), but a
                # real bug for a dataclass field with both an annotation AND
                # a default (`x: list = field(default_factory=list)`, the
                # normal shape for every trailing/optional field in this
                # file's own AST-node dataclasses): the struct-field scanner
                # that builds struct_field_types only recognized VarDecl (no
                # value = pure declaration), so every such field was
                # invisible to the self-hosted compiled path — found via
                # StructDef's own _fieldwise_ctor_synthesized field aborting
                # through the generic getattr fallback. Switching this whole
                # branch to VarDecl (instead of adding type_ann to
                # AssignStmt) turned out to have a much wider blast radius:
                # every module-level `X: dict = {...}`-style global is
                # driven by machinery keyed on `isinstance(stmt, AssignStmt)`
                # (global C-storage boxing, _toplevel() statement collection)
                # that doesn't know about VarDecl — so stick the annotation
                # directly on AssignStmt instead, touching nothing else.
                return AssignStmt(target=expr, value=val, type_ann=type_ann, line=line, col=col)
            else:
                # Bare annotation (e.g. class field `kind: str`) → VarDecl for struct fields.
                # NOTE: this codegen's ternary always evaluates BOTH branches (no
                # real short-circuiting), so `expr.name if isinstance(expr, IdentExpr)
                # else None` would call `.name` unconditionally even when expr isn't
                # an IdentExpr — falling to the dynamic-getattr runtime path, which
                # aborts by design for an unresolvable static type. Use a real `if`
                # instead. Found via example_imports.mojo's module docstring.
                name = None
                if isinstance(expr, IdentExpr):
                    name = expr.name
                if name:
                    return VarDecl(name=name, type_ann=type_ann, value=None, line=line, col=col)
                return ExprStmt(expr, line=line, col=col)
        # Assignment / augmented assignment
        if self._peek().kind == "ASSIGN":
            self._advance()
            val = self._parse_expr(0)
            if self._peek().kind == "ASSIGN":
                targets = [expr]
                while True:
                    if self._peek().kind != "ASSIGN": break
                    targets.append(val)
                    self._advance()
                    val = self._parse_expr(0)
                return MultiAssignStmt(targets=targets, value=val, line=line, col=col)
            # Implicit (parenthesis-less) tuple RHS: `__slots__ = 'a', 'b', 'c'`
            # — a bare comma-separated list on the right of `=` is a tuple.
            if self._peek().kind == "COMMA":
                rhs_elements = [val]
                while self._peek().kind == "COMMA":
                    self._advance()
                    if self._peek().kind in ("NEWLINE", "DEDENT", "EOF"):
                        break
                    rhs_elements.append(self._parse_expr(0))
                val = TupleExpr(elements=rhs_elements)
            return AssignStmt(target=expr, value=val, line=line, col=col)
        if self._peek().kind == "AUGASSIGN":
            op = self._advance().value
            val = self._parse_expr(0)
            return AugAssignStmt(target=expr, op=op, value=val, line=line, col=col)
        self._skip_newlines()
        return ExprStmt(expr, line=line, col=col)

    def _parse_import(self):
        t = self._peek()
        self._expect("KW", "import")
        module, alias = self._parse_import_target()
        # `import a, b, c` — comma-separated module list
        extra = None
        while self._peek().kind == "COMMA":
            self._advance()
            if extra is None:
                extra = []
            extra.append(self._parse_import_target())
        return ImportStmt(module=module, alias=alias, extra=extra,
                          line=t.line, col=t.col)

    def _parse_import_target(self):
        # Handle relative imports: import .warp, import ..sibling
        module = ""
        while self._peek().kind == "DOT":
            self._advance()
            module += "."
        # Module names may collide with keywords (e.g. a module named `comptime`),
        # so accept NAME or KW via _ident().
        module += self._ident()
        while self._peek().kind == "DOT":
            self._advance()
            module += "." + self._ident()
        alias = None
        if self._is_kw("as"):
            self._advance(); alias = self._ident()
        return (module, alias)

    def _parse_from_import(self):
        t = self._peek()
        self._expect("KW", "from")
        # Handle relative imports: from . or from .. or from .module
        module = ""
        while self._peek().kind == "DOT":
            self._advance()
            module += "."
        # If not just dots, parse the module name. Accept a keyword-named
        # module (e.g. `from struct import pack` — `struct` lexes as KW), but
        # never swallow the `import` keyword itself as the module name.
        if self._peek().kind == "NAME" or (self._peek().kind == "KW" and not self._is_kw("import")):
            module += self._advance().value
            while self._peek().kind == "DOT":
                self._advance()
                module += "." + self._ident()
        elif not module:
            # No dots and no name: error
            self._expect("NAME")  # Will raise error
        self._expect("KW", "import")
        if self._peek().kind == "OP" and self._peek().value == "*":
            self._advance()
            return FromImportStmt(module=module, names=[], wildcard=True, line=t.line, col=t.col)
        # Handle parenthesized multi-line imports: from x import (a, b, c)
        paren_import = False
        if self._peek().kind == "LPAREN":
            self._advance()
            paren_import = True
        names = []
        # Parse first name, skipping any leading newlines in parenthesized imports
        if paren_import:
            while self._peek().kind == "NEWLINE": self._advance()
        if self._peek().kind == "RPAREN":
            # Empty parens: from x import ()
            self._advance()
            return FromImportStmt(module=module, names=names, wildcard=False, line=t.line, col=t.col)
        # `_ident()` (not `_expect("NAME")`): an imported name may collide with
        # a Mojo keyword, e.g. `from weakref import ref` — `ref` lexes as KW.
        name = self._ident()
        alias = None
        if self._is_kw("as"):
            self._advance(); alias = self._ident()
        names.append((name, alias))
        # Parse remaining names
        while True:
            if paren_import:
                while self._peek().kind == "NEWLINE": self._advance()
            if self._peek().kind == "RPAREN":
                self._advance()
                break
            if self._peek().kind != "COMMA":
                break
            self._advance()
            if paren_import:
                while self._peek().kind == "NEWLINE": self._advance()
            if self._peek().kind == "RPAREN":
                self._advance()
                break
            name = self._ident()  # keyword-named imports (e.g. `ref`) allowed
            alias = None
            if self._is_kw("as"):
                self._advance(); alias = self._ident()
            names.append((name, alias))
        return FromImportStmt(module=module, names=names, wildcard=False, line=t.line, col=t.col)

    def _parse_var_decl(self):
        self._expect("KW", 'var')
        # Allow KW, backtick identifiers as variable names (e.g., "out", "fn", `6bit`)
        t = self._peek()
        if t.kind == "NAME": name = self._advance().value
        elif t.kind == "KW": name = self._advance().value
        elif t.kind == "STRING" and t.value.startswith("`"): name = self._advance().value
        elif t.kind == "COLON":
            # Python-style field annotation: "var: type"  (var is the field name)
            name = "var"
        else: raise SyntaxError(f"{self._loc(t)}Expected NAME or KW got {t.kind}({t.value!r})")
        # Check for tuple unpacking (var a, b, c = ...)
        if self._peek().kind == "COMMA":
            names = [name]
            while self._peek().kind == "COMMA":
                self._advance()
                t = self._peek()
                if t.kind == "NAME": names.append(self._advance().value)
                elif t.kind == "KW": names.append(self._advance().value)
                elif self._peek().kind == "ASSIGN": break
                else: break
            # Tuple unpacking: create as single VarDecl with tuple name
            if self._peek().kind == "ASSIGN":
                self._advance()
                value = self._parse_expr(0)
                # Handle tuple RHS: var a, b = x, y
                if self._peek().kind == "COMMA":
                    rhs = [value]
                    while self._peek().kind == "COMMA":
                        self._advance()
                        if self._peek().kind == "NEWLINE": break
                        rhs.append(self._parse_expr(0))
                    value = TupleExpr(elements=rhs)
                return VarDecl(name=",".join(names), type_ann=None, value=value)
            else:
                # No assignment, treat as error or incomplete
                return VarDecl(name=",".join(names), type_ann=None, value=None)
        type_ann = None
        if self._peek().kind == "COLON":
            self._advance()
            type_ann = self._parse_type_ann()
        value = None
        if self._peek().kind == "ASSIGN":
            self._advance(); value = self._parse_expr(0)
        return VarDecl(name=name, type_ann=type_ann, value=value)

    def _parse_if(self):
        self._expect("KW", "if")
        cond = self._parse_expr(0)
        self._expect("COLON")
        body = self._parse_block()
        elifs, else_body = [], None
        self._skip_newlines()
        while self._is_kw("elif"):
            self._advance(); ec = self._parse_expr(0)
            self._expect("COLON"); eb = self._parse_block()
            elifs.append((ec, eb))
            self._skip_newlines()
        if self._is_kw("else"):
            self._advance(); self._expect("COLON")
            else_body = self._parse_block()
        return IfStmt(condition=cond, then_body=body, elifs=elifs, else_body=else_body)

    def _parse_while(self):
        self._expect("KW", "while")
        cond = self._parse_expr(0)
        self._expect("COLON")
        body = self._parse_block()
        else_body = None
        self._skip_newlines()
        if self._is_kw("else"):
            self._advance(); self._expect("COLON")
            else_body = self._parse_block()
        return WhileStmt(condition=cond, body=body, else_body=else_body)

    def _is_match_stmt(self):
        """Lookahead for the `match` soft keyword: it's a match statement
        only if, after the subject expression, the next token before any
        NEWLINE is a top-level `:` — a real expression can never contain a
        bare top-level colon (dict/slice colons are always inside braces/
        brackets, which this tracks via depth). Doesn't consume anything;
        always restores position."""
        saved = self._pos
        self._advance()  # consume 'match'
        depth = 0
        is_match = False
        while True:
            t = self._peek()
            if t.kind in ("NEWLINE", "EOF"):
                break
            if t.kind in ("LPAREN", "LBRACKET", "LBRACE"):
                depth += 1
            elif t.kind in ("RPAREN", "RBRACKET", "RBRACE"):
                depth -= 1
            elif t.kind == "COLON" and depth == 0:
                is_match = True
                break
            self._advance()
        self._pos = saved
        return is_match

    def _parse_match(self):
        self._advance()  # consume 'match' (a NAME token, soft keyword)
        subject = self._parse_expr(0)
        self._expect("COLON")
        self._expect("NEWLINE")
        self._skip_newlines()
        self._expect("INDENT")
        cases = []
        self._skip_newlines()
        while self._peek().kind not in ("DEDENT", "EOF"):
            cases.append(self._parse_match_case())
            self._skip_newlines()
        self._expect("DEDENT")
        return MatchStmt(subject=subject, cases=cases)

    def _parse_match_case(self):
        # 'case' is also a soft keyword (NAME, not KW) — same as real Python.
        t = self._peek()
        if not (t.kind == "NAME" and t.value == "case"):
            raise SyntaxError(f"{self._loc(t)}Expected 'case' got {t.kind}({t.value!r})")
        self._advance()
        # `case _:` (bare wildcard, an IdentExpr named '_') is recognized at
        # match time (interpreter/codegen), not specially here — parsing it
        # as a plain expression pattern keeps this parser simple, and lets
        # `_` combine with an or-pattern list the same as any other pattern.
        patterns = [self._parse_expr(0)]
        while self._peek().kind == "COMMA":
            self._advance()
            if self._peek().kind == "COLON" or self._is_kw("if"):
                break  # trailing comma before guard/colon
            patterns.append(self._parse_expr(0))
        guard = None
        if self._is_kw("if"):
            self._advance()
            guard = self._parse_expr(0)
        self._expect("COLON")
        body = self._parse_block()
        return MatchCase(patterns=patterns, body=body, guard=guard)

    def _parse_for(self):
        _for_tok = self._peek()
        self._expect("KW", "for")
        # Skip optional convention keyword (var, ref, mut, etc.) — but only
        # when it's genuinely a prefix, i.e. something that can start a
        # target follows it (another name, or `(` for tuple unpacking).
        # `var` is BOTH a convention keyword (`for var x in y:`, never
        # actually used anywhere in this codebase — grepped) AND a
        # perfectly ordinary Python identifier for the loop variable
        # itself (`for var in (...):`, real code in imports.py). Without
        # the peek(1) check, `for var in (...):` swallowed `var` as a
        # bogus convention prefix, then swallowed `in` too (mistaking it
        # for the loop-variable name), leaving the parser expecting `in`
        # but finding the tuple's `(` instead — "Expected KW got LPAREN".
        if (self._peek().kind == "KW" and self._peek().value in self._CONV_KWS
                and not (self._peek(1).kind == "KW" and self._peek(1).value == "in")
                and self._peek(1).kind != "COLON"):
            self._advance()

        def _parse_for_target():
            """Parse a for-loop target, supporting nested tuples: (a, (b, c))."""
            if self._peek().kind == "LPAREN":
                self._advance()
                parts = []
                while self._peek().kind != "RPAREN" and self._peek().kind != "EOF":
                    parts.append(_parse_for_target())
                    if self._peek().kind == "COMMA":
                        self._advance()
                self._expect("RPAREN")
                return "(" + ", ".join(parts) + ")"
            else:
                tok = self._advance()
                return tok.value

        # Handle tuple unpacking: for (a, b) in ... or for a, b in ...
        if self._peek().kind == "LPAREN":
            target = _parse_for_target()
            # Handle (a, b), c in ...
            if self._peek().kind == "COMMA":
                names = [target]
                while self._peek().kind == "COMMA":
                    self._advance()
                    names.append(_parse_for_target())
                target = "(" + ", ".join(names) + ")"
        else:
            # Accept KW tokens (e.g. "fn", "var") as variable names
            tok = self._advance()
            target = tok.value
            # Handle bare tuple: for a, b in ...
            if self._peek().kind == "COMMA":
                names = [target]
                while self._peek().kind == "COMMA":
                    self._advance()
                    names.append(_parse_for_target())
                target = "(" + ", ".join(names) + ")"
                target = "(" + ", ".join(names) + ")"
        self._expect("KW", "in")
        iterable = self._parse_expr(0)
        # Implicit (parenthesis-less) tuple iterable: `for x in a, b, c:`
        if self._peek().kind == "COMMA":
            elems = [iterable]
            while self._peek().kind == "COMMA":
                self._advance()
                if self._peek().kind == "COLON": break
                elems.append(self._parse_expr(0))
            iterable = TupleExpr(elements=elems)
        self._expect("COLON")
        body = self._parse_block()
        else_body = None
        if self._is_kw("else"):
            self._advance(); self._expect("COLON")
            else_body = self._parse_block()
        return ForStmt(target=target, iterable=iterable, body=body, else_body=else_body,
                       line=_for_tok.line, col=_for_tok.col)

    # Ownership/convention keywords preserved in param_convs
    _CONV_KWS = {'ref', 'out', 'mut', 'var', 'deinit', 'read', 'inout', 'borrowed', 'owned'}
    def _parse_funcdef(self, decorators=None):
        if decorators is None: decorators = []
        # Allow keywords, backtick identifiers as function names (e.g., def read(...), def `6bit`(...))
        t = self._peek()
        if t.kind == "NAME":
            name = self._advance().value
        elif t.kind == "KW":
            name = self._advance().value
        elif t.kind == "STRING" and t.value.startswith("`"):
            name = self._advance().value  # backtick identifier
        else:
            raise SyntaxError(f"{self._loc(t)}Expected NAME or KW got {t.kind}({t.value!r})")
        # Generic type-param block [T: Trait, count: Int, //] — capture the
        # names (see _parse_generic_params_capture) so the interpreter can
        # bind `f[Int32]()`'s subscript to them by position.
        comptime_params = []
        if self._peek().kind == "LBRACKET":
            comptime_params = self._parse_generic_params_capture()
        self._expect("LPAREN")
        params = []
        param_convs = {}
        param_has_default = {}
        kwonly = []
        seen_bare_star = False
        while self._peek().kind != "RPAREN":
            # Skip newlines and indentation within parameter list
            while self._peek().kind in ("NEWLINE", "INDENT", "DEDENT"):
                self._advance()
            if self._peek().kind == "RPAREN": break
            # Capture last argument-convention prefix (read/mut/var/ref/out/deinit)
            # Disambiguation: KW followed by COLON/ASSIGN/COMMA/RPAREN is a param name, not a convention
            conv = None
            while self._peek().kind == "KW" and self._peek().value in self._CONV_KWS:
                if self._peek(1).kind in ("COLON", "ASSIGN", "COMMA", "RPAREN"):
                    break
                conv = self._advance().value
            # Skip positional-only parameter separator /
            if self._peek().kind == "OP" and self._peek().value == "/":
                self._advance()
                if self._peek().kind == "COMMA": self._advance()
                if self._peek().kind == "RPAREN": break
            # Handle ** (keyword variadic parameter: **kwargs)
            if self._peek().kind == "OP" and self._peek().value == "**":
                self._advance()
                t = self._peek()
                if t.kind in ("NAME", "KW"):
                    pname = self._advance().value
                    ptype = None
                    if self._peek().kind == "COLON":
                        self._advance(); ptype = self._parse_type_ann()
                    params.append(("**" + pname, ptype))
                    if conv is not None: param_convs[pname] = conv
                    if self._peek().kind == "COMMA": self._advance()
                    while self._peek().kind in ("NEWLINE", "INDENT", "DEDENT"):
                        self._advance()
                    continue
            # Handle * (keyword-only separator or variadic parameter)
            if self._peek().kind == "OP" and self._peek().value == "*":
                self._advance()
                # Skip lifetime parameters if present after *
                if self._peek().kind == "LBRACKET": self._skip_bracketed()
                # Handle convention keywords after * (e.g., *, var x: Int)
                while self._peek().kind == "KW" and self._peek().value in self._CONV_KWS:
                    if self._peek(1).kind in ("COLON", "ASSIGN", "COMMA", "RPAREN"):
                        break
                    conv = self._advance().value
                # If followed by NAME/KW, it's a variadic parameter (*args) or keyword-only param
                t = self._peek()
                if t.kind in ("NAME", "KW"):
                    if t.kind == "NAME": pname = self._advance().value
                    else: pname = self._advance().value
                    ptype = None
                    if self._peek().kind == "COLON":
                        self._advance(); ptype = self._parse_type_ann()
                    if self._peek().kind == "ASSIGN":
                        self._advance(); self._parse_expr(0)
                        param_has_default[pname] = True
                    params.append(("*" + pname, ptype))
                    if conv is not None: param_convs[pname] = conv
                    if self._peek().kind == "COMMA": self._advance()
                    while self._peek().kind in ("NEWLINE", "INDENT", "DEDENT"):
                        self._advance()
                    continue
                # Otherwise it's a separator: skip following comma and check for end
                elif self._peek().kind == "COMMA": self._advance()
                seen_bare_star = True
                if self._peek().kind == "RPAREN": break
                # Continue to next parameter (convention keywords might follow)
                continue
            if self._peek().kind == "RPAREN": break
            # Skip lifetime parameters in brackets: ref[origin] param_name
            if self._peek().kind == "LBRACKET": self._skip_bracketed()
            # Allow KW tokens as parameter names (e.g., "if", "out")
            t = self._peek()
            if t.kind == "NAME": pname = self._advance().value
            elif t.kind == "KW": pname = self._advance().value
            else: raise SyntaxError(f"{self._loc(t)}Expected NAME or KW got {t.kind}({t.value!r})")
            ptype = None
            if self._peek().kind == "COLON":
                self._advance(); ptype = self._parse_type_ann()
            # Default value =expr: parsed and discarded (no comptime evaluator here),
            # but its mere presence narrows this param's contribution to the
            # function's minimum callable arity — needed for overload resolution.
            if self._peek().kind == "ASSIGN":
                self._advance(); self._parse_expr(0)
                param_has_default[pname] = True
            params.append((pname, ptype))
            if conv is not None: param_convs[pname] = conv
            if seen_bare_star: kwonly.append(pname)
            # Skip trailing comma and newlines
            if self._peek().kind == "COMMA": self._advance()
            while self._peek().kind in ("NEWLINE", "INDENT", "DEDENT"):
                self._advance()
        self._expect("RPAREN")
        # Skip optional `raises` keyword and exception types (must come before return type)
        if self._is_kw("raises"):
            self._advance()  # skip raises
            # Skip exception type list: Type1, Type2, ... until we see -> or : or where
            while self._peek().kind not in ("COLON", "NEWLINE", "EOF", "ARROW"):
                # Stop at 'where' keyword to allow the where-clause handler below
                if self._peek().kind == "NAME" and self._peek().value == "where": break
                if self._peek().kind in ("NAME", "DOT", "STRING", "COMMA"):
                    self._advance()
                elif self._peek().kind == "LBRACKET":
                    self._skip_bracketed()  # Skip subscripted exception types like ExcType[Param]
                else:
                    break
        # Skip function qualifiers (unified, register_passable, capturing, raises,
        # calling-convention markers thin/abi("C"), etc.)
        # ('raises' lexes as a keyword, the rest as names.)
        while self._peek().kind in ("NAME", "KW") and self._peek().value in ("unified", "register_passable", "capturing", "raises", "thin", "abi"):
            self._advance()
            # abi may take a parenthesized convention string: abi("C")
            if self._peek().kind == "LPAREN":
                self._advance()  # consume LPAREN
                depth = 1
                while depth > 0:
                    t = self._advance()
                    if t.kind == "LPAREN":
                        depth += 1
                    elif t.kind == "RPAREN":
                        depth -= 1
                    elif t.kind == "EOF": break
        ret = None
        if self._peek().kind == "ARROW":
            self._advance()
            # Drop `ref` lifetime prefix on return type and skip lifetime parameters
            if self._is_kw("ref"):
                self._advance()
                # Skip lifetime parameters in brackets: ref[Origin]
                if self._peek().kind == "LBRACKET":
                    self._skip_bracketed()
            ret = self._parse_type_ann()
            # Skip additional qualifiers after return type
            while self._peek().kind == "NAME" and self._peek().value in ("unified", "register_passable", "capturing", "raises"):
                self._advance()
        # Skip optional `where conforms_to(...)` clause
        if self._peek().kind == "NAME" and self._peek().value == "where":
            self._advance()  # where
            while self._peek().kind not in ("COLON", "NEWLINE", "EOF"):
                self._advance()
        # Skip capture lists in curly braces (for closures/lambdas)
        if self._peek().kind == "LBRACE":
            self._advance()  # {
            depth = 1
            while depth > 0:
                t = self._advance()
                if t.kind == "LBRACE":
                    depth += 1
                elif t.kind == "RBRACE":
                    depth -= 1
                elif t.kind == "EOF": break
        # Return type may appear after the capture list
        if ret is None and self._peek().kind == "ARROW":
            self._advance()
            if self._is_kw("ref"):
                self._advance()
                if self._peek().kind == "LBRACKET":
                    self._skip_bracketed()
            ret = self._parse_type_ann()
        self._expect("COLON")
        body = self._parse_block()
        return FunctionDef(name=name, params=params, return_type=ret,
                           body=body, decorators=decorators,
                           param_convs=param_convs,
                           param_has_default=param_has_default,
                           kwonly=kwonly,
                           comptime_params=comptime_params)

    def _parse_struct(self):
        # Accept both "struct" and "class" keywords
        kw = self._peek()
        if kw.kind == "KW" and kw.value in ("struct", "class"):
            self._advance()
        else:
            self._expect("KW", "struct")
        name = self._expect("NAME").value
        # Parse struct parameter block [x: Type, y: Type = default, ...] as fields
        param_fields = []
        if self._peek().kind == "LBRACKET":
            param_fields = self._parse_struct_params_as_fields()
        # `struct Child(Base1, Base2):` / `class Child(Base):` — Python-style
        # base-class list. Capture the top-level names (skipping keyword
        # args like `metaclass=X` and trait-bound expressions we can't
        # resolve as a real base) instead of discarding the whole
        # parenthesized list; MojoClass merges the named bases' fields and
        # methods at struct-definition time (see execute_StructDef).
        bases = []
        if self._peek().kind == "LPAREN":
            self._advance()
            depth = 1
            expect_name = True
            while depth > 0:
                t = self._peek()
                if t.kind == "LPAREN":
                    self._advance(); depth += 1; continue
                if t.kind == "RPAREN":
                    self._advance(); depth -= 1; continue
                if t.kind == "EOF":
                    break
                if t.kind == "COMMA" and depth == 1:
                    self._advance(); expect_name = True; continue
                if depth == 1 and expect_name and t.kind == "NAME":
                    nxt = self._peek(1)
                    is_kwarg = nxt.kind in ("ASSIGN", "EQUAL") or (
                        nxt.kind == "OP" and nxt.value == "=")
                    if not is_kwarg:
                        bases.append(t.value)
                    self._advance()
                    expect_name = False
                    continue
                self._advance()
        self._expect("COLON")
        body = self._parse_block()
        fields  = param_fields + [s for s in body if isinstance(s, (VarDecl, AssignStmt))]
        methods = [s for s in body if isinstance(s, FunctionDef)]
        # Struct-level `comptime NAME = expr` are aliases, not physical fields.
        # Capture them so member access can expand `self.NAME` to its expression
        # (this codegen does not monomorphize, so e.g. _words_size depends on the
        # runtime `size` field).
        aliases = {s.target: s.value for s in body if isinstance(s, ComptimeVarStmt)}
        decs    = getattr(self, "_pending_decs", [])
        self._pending_decs = []
        return StructDef(name=name, fields=fields, methods=methods, decorators=decs,
                         comptime_aliases=aliases, bases=bases)

    def _parse_trait(self):
        self._expect("KW", "trait")
        name = self._expect("NAME").value
        # Skip generic type-param block [T: Trait, ...]
        if self._peek().kind == "LBRACKET": self._skip_bracketed()
        if self._peek().kind == "LPAREN":
            self._advance()
            # Skip balanced parentheses in trait list
            depth = 1
            while depth > 0:
                t = self._advance()
                if t.kind == "LPAREN":
                    depth += 1
                elif t.kind == "RPAREN":
                    depth -= 1
                elif t.kind == "EOF":
                    break
        self._expect("COLON")
        body = self._parse_block()
        methods = [s for s in body if isinstance(s, FunctionDef)]
        decs = getattr(self, "_pending_decs", [])
        self._pending_decs = []
        return TraitDef(name=name, methods=methods)

    def _parse_try(self):
        self._expect("KW", "try"); self._expect("COLON")
        body = self._parse_block()
        handlers = []
        while self._is_kw("except"):
            self._advance()
            # `except*` exception groups (PEP 654): the star is cosmetic for
            # our tag-based dispatch — accept and ignore it.
            if self._peek().kind == "OP" and self._peek().value == "*":
                self._advance()
            exc_type, exc_name = None, None
            if self._peek().kind == "LPAREN":
                # Parenthesized tuple of exception types:
                #   except (ValueError, TypeError):
                # Stored as a list of dotted-name strings; codegen ORs the
                # tag match across every type in the tuple.
                self._advance()
                names = []
                while self._peek().kind != "RPAREN":
                    names.append(self._parse_dotted_name())
                    if self._peek().kind == "COMMA": self._advance()
                    else: break
                self._expect("RPAREN")
                exc_type = names
                if self._is_kw("as"):
                    self._advance(); exc_name = self._ident()
            elif self._peek().kind in ("NAME", "KW") and not self._is_kw("as"):
                # A single (possibly dotted) exception type, e.g.
                #   except ValueError:      except asyncio.CancelledError:
                exc_type = self._parse_dotted_name()
                if self._is_kw("as"):
                    self._advance(); exc_name = self._ident()
            self._expect("COLON")
            handlers.append(ExceptHandler(exc_type=exc_type, name=exc_name,
                                           body=self._parse_block()))
        else_body = None
        if self._is_kw("else"):
            self._advance(); self._expect("COLON"); else_body = self._parse_block()
        finally_body = None
        if self._is_kw("finally"):
            self._advance(); self._expect("COLON"); finally_body = self._parse_block()
        return TryStmt(body=body, handlers=handlers,
                       else_body=else_body, finally_body=finally_body)

    def _parse_with(self):
        self._expect("KW", "with")
        items = []
        # `as` in a with-item's own `expr as alias` clause is NOT the binary
        # cast operator (_KW_PREC['as']) — parse at one above its precedence
        # so the operator loop stops before swallowing the alias as a
        # BinaryOp(op='as', ...) right-hand side.
        with_expr_prec = _KW_PREC['as'] + 1
        expr = self._parse_expr(with_expr_prec)
        alias = None
        if self._is_kw("as"):
            self._advance(); alias = self._ident()
        items.append(WithItem(expr=expr, alias=alias))
        while self._peek().kind == "COMMA":
            self._advance(); expr = self._parse_expr(with_expr_prec); alias = None
            if self._is_kw("as"):
                self._advance(); alias = self._ident()
            items.append(WithItem(expr=expr, alias=alias))
        self._expect("COLON")
        return WithStmt(items=items, body=self._parse_block())

    def _parse_comptime(self):
        self._expect("KW", "comptime")
        t = self._peek()
        if t.value == "if":  return self._parse_comptime_if()
        if t.value == "for": return self._parse_comptime_for()
        # comptime assert expr[, msg]
        if t.value == "assert": return self._parse_assert()
        # comptime NAME [TypeParams] [: Type] = expr
        # Also allow backtick-quoted identifiers: comptime `A` = Byte(ord("A"))
        if t.kind == "NAME" or (t.kind == "STRING" and t.value.startswith("`")):
            name = self._advance().value
            # Skip optional type parameters: comptime Alias[T, U]: Type = ...
            if self._peek().kind == "LBRACKET": self._skip_bracketed()
            # Skip optional type annotation: comptime MIN: Bool = False
            if self._peek().kind == "COLON":
                self._advance()  # skip colon
                self._parse_type_ann()  # parse and discard type annotation
            if self._peek().kind == "ASSIGN":
                self._advance()
                # Parse/skip RHS expression, handling complex function types
                rhs = self._skip_comptime_rhs()
                return ComptimeVarStmt(target=name, value=rhs)
            return ExprStmt(IdentExpr(name))
        raise SyntaxError(f"{self._loc(t)}Unexpected token after comptime: {t.value!r}")

    def _skip_comptime_rhs(self):
        """Parse RHS of comptime assignment, with fallback for complex types.

        Comptime variables are compile-time only and shouldn't generate runtime code.
        Try to parse simple literals/calls; for complex types (def[...] -> ...), skip them.
        """
        t = self._peek()

        # Check for function type definitions — skip to newline
        if (t.kind == "KW" and t.value == "def") or self._will_see_arrow():
            depth = 0
            while self._peek().kind not in ("NEWLINE", "DEDENT", "EOF"):
                t = self._peek()
                if t.kind in ("LBRACKET", "LPAREN"):
                    depth += 1
                elif t.kind in ("RBRACKET", "RPAREN"):
                    depth -= 1
                    if depth < 0: break
                self._advance()
            return IdentExpr("_comptime_expr")

        # Try to parse simple expressions (literals, identifiers, simple calls)
        saved_pos = self._pos
        try:
            expr = self._parse_expr(0)
            return expr
        except:
            # Fallback: skip to newline
            self._pos = saved_pos
            while self._peek().kind not in ("NEWLINE", "DEDENT", "EOF"):
                self._advance()
            return IdentExpr("_comptime_expr")

    def _will_see_arrow(self):
        """Lookahead to check if we'll see a -> at bracket depth 0 before NEWLINE."""
        saved = self._pos
        depth = 0
        while self._peek().kind not in ("NEWLINE", "DEDENT", "EOF"):
            t = self._peek()
            if t.kind == "ARROW" and depth == 0:
                self._pos = saved
                return True
            if t.kind in ("LBRACKET", "LPAREN"):
                depth += 1
            elif t.kind in ("RBRACKET", "RPAREN"):
                depth -= 1
            self._advance()
        self._pos = saved
        return False

    def _parse_comptime_if(self):
        self._expect("KW","if"); cond=self._parse_expr(0)
        self._expect("COLON"); body=self._parse_block()
        elifs, else_body = [], None
        while self._is_kw("elif"):
            self._advance(); ec = self._parse_expr(0)
            self._expect("COLON"); eb = self._parse_block()
            elifs.append((ec, eb))
        if self._is_kw("else"):
            self._advance();self._expect("COLON");else_body=self._parse_block()
        return ComptimeIfStmt(condition=cond,then_body=body,elifs=elifs,else_body=else_body)

    def _parse_comptime_for(self):
        self._expect("KW","for")
        # Optional convention keyword (var, ref, ...) before the target
        if self._peek().kind == "KW" and self._peek().value in self._CONV_KWS:
            self._advance()
        # Support tuple targets: comptime for i, j in product(...)
        target = self._ident()
        if self._peek().kind == "COMMA":
            names = [target]
            while self._peek().kind == "COMMA":
                self._advance()
                if self._is_kw("in"): break
                names.append(self._ident())
            target = "(" + ", ".join(names) + ")"
        self._expect("KW","in"); iterable=self._parse_expr(0)
        self._expect("COLON")
        return ComptimeForStmt(target=target,iterable=iterable,body=self._parse_block())

    def _parse_pass(self):
        t = self._peek()
        self._expect("KW", 'pass')
        return PassStmt(line=t.line, col=t.col)

    def _parse_return(self):
        t = self._peek()
        self._expect("KW", 'return')
        if self._peek().kind in ("NEWLINE","EOF","DEDENT"):
            return ReturnStmt(value=None, line=t.line, col=t.col)
        expr = self._parse_expr(0)
        # Check for tuple return: return a, b, c
        if self._peek().kind == "COMMA":
            elements = [expr]
            while self._peek().kind == "COMMA":
                self._advance()
                if self._peek().kind in ("NEWLINE", "DEDENT", "EOF"):
                    break
                elements.append(self._parse_expr(0))
            # A separate variable, not reassigning `expr` — `expr` is first
            # assigned from self._parse_expr(0) (an opaque/boxed Expr
            # subtype, compiled as generic int64_t), then would be
            # reassigned here to a real TupleExpr(...) constructor call.
            # Joining those two assignment sites' types made the compiled
            # local's declared C type `TupleExpr *` (the type-join rule
            # "one pointer, one non-pointer -> use the pointer type" doesn't
            # know the "non-pointer" int64_t side is itself an opaquely
            # boxed pointer of some OTHER concrete type) — but `expr.line`/
            # `expr.col` just below read the ORIGINAL boxed value through
            # that wrong, TupleExpr-shaped field layout, misreading garbage
            # off whatever real struct (e.g. IdentExpr) `expr` actually
            # held. Found via `def f(a, b): return a, b` compiling to
            # TupleExpr(..., line=<garbage pointer>, ...) once self-hosted.
            tuple_expr = TupleExpr(elements=elements, line=expr.line, col=expr.col)
            return ReturnStmt(value=tuple_expr, line=t.line, col=t.col)
        return ReturnStmt(value=expr, line=t.line, col=t.col)

    def _parse_raise(self):
        self._expect("KW", 'raise')
        if self._peek().kind in ("NEWLINE","EOF","DEDENT"):
            return RaiseStmt(value=None)
        val = self._parse_expr(0)
        # `raise X from Y` / `raise X from None` — exception-chaining
        # suppression. The cause is not modeled by our tag-based exception
        # runtime, but must be consumed so parsing continues past it.
        if self._is_kw("from"):
            self._advance(); self._parse_expr(0)
        return RaiseStmt(value=val)

    def _parse_break(self):
        self._expect("KW", 'break')
        return BreakStmt()

    def _parse_continue(self):
        self._expect("KW", 'continue')
        return ContinueStmt()

    def _parse_assert(self):
        t = self._expect("KW", 'assert')
        value = self._parse_expr(0)
        msg = None
        if self._peek().kind == "COMMA":
            self._advance(); msg = self._parse_expr(0)
        return AssertStmt(value=value, msg=msg, line=t.line, col=t.col)

    def _parse_global(self):
        t = self._peek()
        self._expect("KW", 'global')
        names = []
        names.append(self._expect("NAME").value)
        while self._peek().kind == "COMMA":
            self._advance()
            if self._peek().kind in ("NEWLINE", "DEDENT", "EOF"):
                break
            names.append(self._expect("NAME").value)
        return GlobalStmt(names=names, line=t.line, col=t.col)

    # ── Expressions ──────────────────────────────────────────────────
    def _parse_expr(self, min_prec: int):
        # Boolean `not` is a low-precedence prefix operator (binds looser than
        # comparison/`in`, tighter than `and`): `not a in b` == `not (a in b)`.
        # The binary `not in` form is handled in the operator loop below.
        if self._peek().kind == "KW" and self._peek().value == "not":
            self._advance()
            operand = self._parse_expr(_KW_PREC['not'])
            left = UnaryOp(op="not", operand=operand)
        else:
            left = self._parse_unary()
        while True:
            t = self._peek()
            if t.kind == "OP":
                prec = _PREC.get(t.value, -1)
                if prec < min_prec: break
                op = self._advance().value
                right = self._parse_expr(prec + 1)
                if op == ":=" and isinstance(left, IdentExpr):
                    left = WalrusExpr(name=left.name, value=right)
                else:
                    left = BinaryOp(op=op, left=left, right=right)
            elif t.kind == "KW" and t.value in _KW_PREC:
                prec = _KW_PREC[t.value]
                if prec < min_prec: break
                op = self._advance().value
                if op == "not" and self._is_kw("in"):
                    self._advance(); op = "not in"
                elif op == "is" and self._is_kw("not"):
                    self._advance(); op = "is not"
                right = self._parse_expr(prec + 1)
                left = BinaryOp(op=op, left=left, right=right)
            elif t.kind == "KW" and t.value == "if" and min_prec == 0:
                self._advance()
                cond = self._parse_expr(1)
                self._expect("KW", "else")
                els = self._parse_expr(0)
                left = TernaryExpr(condition=cond, then_val=left, else_val=els)
            else:
                break
        return left

    def _parse_unary(self):
        t = self._peek()
        # `await expr` — `await` lexes as a plain NAME (not a keyword). Async
        # semantics aren't modeled, so unwrap to the awaited expression. Guard
        # on the next token starting an expression so a variable literally
        # named `await` (`x = await`, `await.foo`) still reads as an identifier.
        if (t.kind == "NAME" and t.value == "await"
                and self._peek(1).kind in ("NAME", "KW", "STRING", "INT",
                    "FLOAT", "LPAREN", "LBRACKET", "LBRACE")):
            self._advance()
            return self._parse_unary()
        if t.kind == "OP" and t.value in ("-", "+", "~"):
            self._advance()
            return UnaryOp(op=t.value, operand=self._parse_unary())
        # Boolean `not` is handled as a low-precedence prefix in _parse_expr.
        # Spread/unpack: *expr or **expr (valid inside list/dict/call literals).
        # `**` lexes as a single OP token, so handle it directly — otherwise
        # dict unpacking `{**a, **b}` hit the fallthrough "Unexpected OP('**')".
        if t.kind == "OP" and t.value == "**":
            self._advance()
            return UnaryOp(op="**", operand=self._parse_unary())
        if t.kind == "OP" and t.value == "*":
            self._advance()
            # Check for **
            if self._peek().kind == "OP" and self._peek().value == "*":
                self._advance()
                return UnaryOp(op="**", operand=self._parse_unary())
            return UnaryOp(op="*", operand=self._parse_unary())
        return self._parse_postfix()

    def _parse_subscript_item(self):
        """Parse one subscript element: a slice (`start:stop:step`, every part
        optional) or a plain expression. Slices are returned as a SliceExpr with
        obj=None (the caller attaches the object); plain indices are returned as
        the bare expression node. Used for both 1-D and multi-dim (`a[0:2, ::]`)
        indexing."""
        start = None
        if self._peek().kind != "COLON":
            start = self._parse_expr(0)
            # Function-type annotation in type position: def(...) [quals] -> T
            self._skip_fn_quals()
            if self._peek().kind == "ARROW":
                self._advance(); self._parse_type_ann()
            if self._peek().kind != "COLON":
                return start  # plain index, not a slice
        # At a COLON → this element is a slice.
        self._advance()
        stop = (None if self._peek().kind in ("RBRACKET", "COMMA", "COLON")
                else self._parse_expr(0))
        step = None
        if self._peek().kind == "COLON":
            self._advance()
            step = (None if self._peek().kind in ("RBRACKET", "COMMA")
                    else self._parse_expr(0))
        return SliceExpr(obj=None, start=start, stop=stop, step=step)

    def _parse_postfix(self):
        expr = self._parse_primary()
        while True:
            t = self._peek()
            line, col = t.line, t.col
            if t.kind == "DOT":
                self._advance()
                # Member can be a NAME (including KW like mut, ref) or a backtick-quoted type
                if self._peek().kind == "STRING" and self._peek().value.startswith("`"):
                    member = self._advance().value
                elif self._peek().kind in ("NAME", "KW"):
                    member = self._advance().value
                else:
                    member = self._expect("NAME").value  # error for invalid syntax
                expr = MemberExpr(obj=expr, member=member, line=line, col=col)
            elif t.kind == "LBRACKET":
                self._advance()
                # Check for empty subscript [] (dereference/special case)
                if self._peek().kind == "RBRACKET":
                    idx = IntLiteral(value=0)  # dummy index for empty subscript
                    self._advance()  # consume RBRACKET
                    expr = SubscriptExpr(obj=expr, index=idx)
                else:
                    # Parse first index/argument
                    # Check for unpacking: *expr
                    if self._peek().kind == "OP" and self._peek().value == "*":
                        self._advance()  # skip *
                        self._parse_expr(0)  # parse and discard unpacked value
                        # Continue parsing remaining arguments
                        while self._peek().kind == "COMMA":
                            self._advance()
                            if self._peek().kind == "RBRACKET": break
                            # Skip remaining arguments/keywords
                            if self._peek().kind == "OP" and self._peek().value == "*":
                                self._advance()
                                self._parse_expr(0)
                            elif self._peek().kind in ("NAME", "KW") and self._peek(1).kind == "ASSIGN":
                                self._advance()  # skip name
                                self._advance()  # skip =
                                self._parse_expr(0)
                            else:
                                self._parse_expr(0)
                            if self._peek().kind != "COMMA" and self._peek().kind != "RBRACKET": break
                        self._expect("RBRACKET")
                        expr = SubscriptExpr(obj=expr, index=IntLiteral(value=0))
                    # Check if this is a keyword-style bracket (func=value, attr=value)
                    elif self._peek().kind in ("NAME", "KW") and self._peek(1).kind == "ASSIGN":
                        # Keyword arguments (may include positional args with dotted names and slice values).
                        # We keep (name, value) pairs in `attrs` so consumers that
                        # need them survive — notably MLIR op params like
                        # __mlir_op.`index.cmp`[pred=__mlir_attr.`...`](...).
                        _attrs = []
                        while self._peek().kind != "RBRACKET" and self._peek().kind != "EOF":
                            if self._peek().kind in ("NAME", "KW"):
                                # Parse the full expression for the arg (handles dotted names Self.Ts, subscripts, etc.)
                                arg_expr = self._parse_expr(0)
                                if self._peek().kind == "ASSIGN":
                                    # keyword arg: advance = and parse the value,
                                    # which may itself be a slice (key = -50::) or
                                    # a function type. _parse_subscript_item handles
                                    # all of start:stop:step, fn-types, and exprs.
                                    self._advance()
                                    _val = self._parse_subscript_item()
                                    # Real `if`, not a ternary: this codegen's ternary
                                    # always evaluates both branches, so `.name` would
                                    # run even when arg_expr isn't an IdentExpr (see the
                                    # identical fix + note in _parse_stmt's bare-annotation
                                    # branch above).
                                    _name = None
                                    if isinstance(arg_expr, IdentExpr):
                                        _name = arg_expr.name
                                    _attrs.append((_name, _val))
                                # else positional arg: arg_expr already fully parsed
                            # Handle ellipsis (...) as an argument (three DOTs)
                            elif (self._peek().kind == "DOT" and
                                  self._peek(1).kind == "DOT" and
                                  self._peek(2).kind == "DOT"):
                                self._advance(); self._advance(); self._advance()
                            if self._peek().kind == "COMMA": self._advance()
                            elif self._peek().kind != "RBRACKET": break
                        self._expect("RBRACKET")
                        expr = SubscriptExpr(obj=expr, index=IntLiteral(value=0), attrs=_attrs)
                    else:
                        # Parse a comma-separated list of subscript items. Each
                        # item is a slice (start:stop:step) or a plain expression,
                        # so this covers 1-D slicing (a[1:2]), generic params
                        # (List[T, n]), and multi-dim slicing (a[0:2, ::]).
                        items = [self._parse_subscript_item()]
                        while self._peek().kind == "COMMA":
                            self._advance()
                            if self._peek().kind == "RBRACKET": break
                            # Unpacking: *expr
                            if self._peek().kind == "OP" and self._peek().value == "*":
                                self._advance()
                                items.append(self._parse_expr(0))
                            # Keyword argument: name = value (generic params)
                            elif self._peek().kind in ("NAME", "KW") and self._peek(1).kind == "ASSIGN":
                                self._advance()  # name
                                self._advance()  # =
                                items.append(self._parse_subscript_item())
                            # Ellipsis: ...
                            elif (self._peek().kind == "DOT" and
                                  self._peek(1).kind == "DOT" and
                                  self._peek(2).kind == "DOT"):
                                self._advance(); self._advance(); self._advance()
                                items.append(EllipsisLiteral())
                            else:
                                items.append(self._parse_subscript_item())
                        self._expect("RBRACKET")
                        if len(items) == 1:
                            only = items[0]
                            if isinstance(only, SliceExpr):
                                only.obj = expr  # attach object to the bare slice
                                expr = only
                            else:
                                expr = SubscriptExpr(obj=expr, index=only)
                        else:
                            expr = SubscriptExpr(obj=expr, index=TupleExpr(elements=items))
            elif t.kind == "LPAREN":
                self._advance()
                args = []
                keywords = {}
                while self._peek().kind != "RPAREN":
                    # Handle dictionary unpacking (**expr)
                    if self._peek().kind == "OP" and self._peek().value == "**":
                        self._advance()  # skip **
                        args.append(self._parse_expr(0))  # parse unpacked kwargs
                    # Handle unpacking (*expr)
                    elif self._peek().kind == "OP" and self._peek().value == "*":
                        self._advance()  # skip *
                        args.append(self._parse_expr(0))  # parse unpacked value
                    # Handle keyword arguments (name=value) — name can be NAME or KW token
                    elif self._peek().kind in ("NAME", "KW") and self._peek(1).kind == "ASSIGN":
                        keyword_name = self._advance().value  # get keyword name
                        self._advance()  # skip =
                        keywords[keyword_name] = self._parse_expr(0)  # parse and store value
                    else:
                        first = self._parse_expr(0)
                        if self._is_kw("for"):
                            gens = self._parse_generators()  # allow chained for-clauses
                            args = [Comprehension(kind="generator", element=first, generators=gens)]
                            continue
                        args.append(first)
                    if self._peek().kind == "COMMA": self._advance()
                self._expect("RPAREN")
                # Convert keywords dict to list of (name, expr) tuples for CallExpr.kwargs
                kwargs_list = [(k, v) for k, v in keywords.items()]
                expr = CallExpr(func=expr, args=args, kwargs=kwargs_list, line=line, col=col)
            elif t.kind == "OP" and t.value == "^":
                # Check if ^ is postfix (ownership transfer) or binary (XOR)
                # Postfix: followed by statement-ending token or member/subscript access
                # Binary: followed by expression start token
                next_t = self._peek(1)
                is_postfix = next_t.kind in ("NEWLINE", "DEDENT", "EOF", "COMMA", "RPAREN", "RBRACKET", "RBRACE", "COLON", "SEMICOLON", "DOT", "LBRACKET")
                if is_postfix:
                    self._advance()
                    expr = UnaryOp(op="^", operand=expr, line=line, col=col)
                else:
                    break  # Let binary operator precedence handle it
            else:
                break
        return expr

    def _strip_string_prefix_and_quotes(self, raw: str) -> str:
        """A STRING token's value may carry a prefix (f/F/r/R/b/B/u/U/t/T,
        0-2 chars) before the quotes. F-strings and t-strings deliberately
        KEEP their prefix+quotes in the StringLiteral value (both
        gimple_codegen.py's _lower_StringLiteral and myinterpreter.py's
        eval_StringLiteral need the prefix, to know interpolation is needed
        and to tell the two apart) but every other prefixed string (r'...',
        b'...', rb'...', etc.) must have BOTH the prefix and the quotes
        stripped — this previously only stripped quotes when the raw token
        started with a quote character directly, silently leaving any r/b/u
        prefix as literal text in the StringLiteral's value for every non-f
        prefixed string. Found via reflect.py's own
        `_PROTO_RE = re.compile(r'...')`: the compiled StringLiteral's value
        was the literal text "r'...'" (prefix and quotes included), not the
        real pattern text.
        """
        # NOTE: this codegen's `and`/`or` always evaluate BOTH operands (no
        # real short-circuiting — see gimple_codegen.py's BinaryOp lowering),
        # so every guard below must be a separate nested `if`, never
        # `cond and raw[i]`-style — otherwise the index/slice still runs
        # even when the guard is false and crashes on an empty string.
        # Deliberately avoid `x in "somestring"`/`x in (a, b)`-style checks
        # for the two guards below (prefix-char scan, f/t detection) — this
        # codegen's compiled path has a confirmed, still-open bug where
        # implementing that specific shape of the `in` operator corrupts
        # unrelated state elsewhere (see BACKLOG-CODEGEN.md / the
        # bootstrap-verify-ast-dump-fixes memory note). Explicit `==`
        # comparisons on single characters are a proven-safe, already-used
        # pattern elsewhere in this same function (see the `first == last`
        # comment below) and sidestep that bug entirely.
        prefix_len = 0
        while prefix_len < len(raw) and prefix_len < 2:
            _c = raw[prefix_len]
            _is_prefix_char = (_c == 'f' or _c == 'F' or _c == 'r' or _c == 'R'
                                or _c == 'b' or _c == 'B' or _c == 'u' or _c == 'U'
                                or _c == 't' or _c == 'T')
            if not _is_prefix_char:
                break
            prefix_len += 1
        prefix, rest = raw[:prefix_len], raw[prefix_len:]
        has_quote_after_prefix = False
        if len(rest) >= 1:
            _rc = rest[0]
            if _rc == '"' or _rc == "'":
                has_quote_after_prefix = True
        if not has_quote_after_prefix:
            prefix, rest = '', raw  # no real prefix (nothing quote-like follows it)
        # Compare both cases directly instead of calling .lower() on a raw
        # indexed char (prefix[0]/[1]) — that routes to a runtime helper
        # (char.lower()) this compiler doesn't implement for a bare char,
        # an undefined-symbol link error ("_char_lower"), not a silent bug.
        _has_ft = False
        if len(prefix) >= 1:
            _p0 = prefix[0]
            if _p0 == 'f' or _p0 == 'F' or _p0 == 't' or _p0 == 'T':
                _has_ft = True
        if len(prefix) >= 2:
            _p1 = prefix[1]
            if _p1 == 'f' or _p1 == 'F' or _p1 == 't' or _p1 == 'T':
                _has_ft = True
        if _has_ft:
            return raw
        # Built via concatenation, not written as literal 3-quote runs (see
        # replace_multiline_strings's identical "avoids bootstrap self-match"
        # comment for the same reasoning) — py_tokenize's own docstring
        # placeholder pass has no notion of enclosing-quote context: it
        # matches the FIRST literal triple-quote run it sees in the source
        # and non-greedily extends to the NEXT one found anywhere later, on
        # the assumption both delimit one real multi-line string. Two short,
        # unrelated same-shape literals a few lines apart (a single quote
        # wrapping three double-quote characters, and the mirror case) used
        # to sit right here as literal source text, and that used to be
        # exactly the trigger: self-hosted-compiling THIS function's own
        # body swallowed everything between them as one bogus docstring
        # placeholder, corrupting the compiled function so it always
        # returned false here regardless of the real input — breaking every
        # real triple-quoted docstring's quote-stripping for every
        # self-hosted-compiled program, not just ones with adjacent literals
        # of this shape. Found via bootstrap_test_single_expr.mojo's own
        # plain, isolated docstring picking up two stray extra quote
        # characters once self-hosted. NOTE: keep this whole comment block
        # free of the literal quote-triple shapes described above too — the
        # same self-match hazard applies to comment text, not just code.
        _dq3 = '"' * 3
        _sq3 = "'" * 3
        if len(rest) >= 6:
            if rest.startswith(_dq3) and rest.endswith(_dq3):
                return rest[3:-3]
            if rest.startswith(_sq3) and rest.endswith(_sq3):
                return rest[3:-3]
        if len(rest) >= 2:
            # Compare characters directly (`first == last`) rather than
            # `rest.endswith(rest[0])`: `rest[0]` is a raw single-character
            # scalar (this codegen's string-indexing result), and passing it
            # straight into a call expecting `char *` reinterprets its byte
            # value as a garbage pointer — the same "raw char vs char*"
            # mismatch documented in gimple_codegen.py's _to_char_star, just
            # hit via a call argument instead of a `==` comparison this time.
            first = rest[0]
            last = rest[len(rest) - 1]
            if (first == '"' or first == "'") and first == last:
                return rest[1:-1]
        return raw

    def _parse_primary(self):
        t = self._peek()
        line, col = t.line, t.col
        if t.kind == "INT":
            self._advance(); return IntLiteral(int(t.value, 0), line=line, col=col, raw=t.value)
        if t.kind == "FLOAT":
            self._advance(); return FloatLiteral(float(t.value), line=line, col=col)
        if t.kind == "KW" and t.value in ("True","False"):
            self._advance()
            return BoolLiteral(t.value == "True", line=line, col=col)
        if t.kind == "STRING" and t.value.startswith("`"):
            # Backtick-quoted identifier reference (e.g. `` `3` `` naming a
            # comptime var whose spelling isn't a valid bare NAME token, or
            # `` `6bit` ``-style names — see _parse_comptime/_parse_param's
            # matching special-cases, which store the name INCLUDING its
            # backticks). Without this, a reference (as opposed to a
            # declaration site) fell through to the generic STRING branch
            # below and became a StringLiteral whose value was the literal
            # text "`3`", backticks and all — so e.g. `"mojo" * \`3\`` tried
            # to multiply a str by a str instead of by the int the comptime
            # var held.
            self._advance()
            return IdentExpr(t.value, line=line, col=col)
        if t.kind == "STRING":
            val = self._strip_string_prefix_and_quotes(self._advance().value)
            # Handle implicit string concatenation (adjacent strings)
            while self._peek().kind == "STRING":
                val += self._strip_string_prefix_and_quotes(self._advance().value)
            return StringLiteral(val, line=line, col=col)
        if t.kind == "LBRACKET": return self._parse_list_or_compr()
        if t.kind == "LBRACE": return self._parse_dict_or_set()
        if t.kind == "LPAREN":
            self._advance()
            # Allow an ownership/convention prefix inside a parenthesized binding
            # target, e.g. tuple unpacking `(var x), (ref y) = ...`.
            if (self._peek().kind == "KW" and self._peek().value in self._CONV_KWS
                    and self._peek(1).kind in ("NAME", "KW")):
                self._advance()
            if self._peek().kind == "RPAREN":
                self._advance(); return TupleExpr(elements=[], line=line, col=col)
            first = self._parse_expr(0)
            if self._is_kw("for"):
                # `_parse_generators` (plural) handles chained clauses:
                # (x for row in rows for x in row) — a single `for` clause
                # left the trailing `for` unconsumed → "Expected RPAREN got for".
                gens = self._parse_generators()
                self._expect("RPAREN")
                return Comprehension(kind="generator", element=first, generators=gens, line=line, col=col)
            if self._peek().kind == "COMMA":
                elems = [first]
                while self._peek().kind == "COMMA":
                    self._advance()
                    if self._peek().kind == "RPAREN": break
                    elems.append(self._parse_expr(0))
                self._expect("RPAREN")
                return TupleExpr(elements=elems, line=line, col=col)
            self._expect("RPAREN")
            return first
        if t.kind in ("NAME", "KW"):
            self._advance()
            if t.value == "lambda" and t.kind == "NAME" and (
                self._peek().kind == "COLON"
                or self._peek().kind == "NAME"
                or (self._peek().kind == "OP" and self._peek().value in ("*", "**"))
            ):
                return self._parse_lambda()
            return IdentExpr(t.value, line=line, col=col)
        if t.kind == "DOT" and self._peek(1).kind == "DOT" and self._peek(2).kind == "DOT":
            self._advance(); self._advance(); self._advance()
            return EllipsisLiteral(line=line, col=col)
        raise SyntaxError(f"{self._loc(t)}Unexpected {t.kind}({t.value!r})")

    def _parse_lambda(self):
        params = []
        while self._peek().kind != "COLON":
            if self._peek().kind in ("NEWLINE", "INDENT", "DEDENT"):
                self._advance(); continue
            if self._peek().kind == "RPAREN": break
            if self._peek().kind == "OP" and self._peek().value == "*":
                self._advance()
                if self._peek().kind in ("NAME", "KW"):
                    params.append(("*" + self._advance().value, None))
                continue
            if self._peek().kind == "OP" and self._peek().value == "**":
                self._advance()
                if self._peek().kind in ("NAME", "KW"):
                    params.append(("**" + self._advance().value, None))
                continue
            if self._peek().kind in ("NAME", "KW"):
                pname = self._advance().value
                default = None
                if self._peek().kind == "ASSIGN":
                    self._advance()
                    default = self._parse_expr(0)
                params.append((pname, default))
            if self._peek().kind == "COMMA": self._advance()
        self._expect("COLON")
        body = self._parse_expr(0)
        return LambdaExpr(params=params, body=body)

    def _parse_list_or_compr(self):
        self._expect("LBRACKET")
        if self._peek().kind == "RBRACKET":
            self._advance(); return ListExpr(elements=[])
        first = self._parse_expr(0)
        if self._is_kw("for"):
            gens = self._parse_generators()
            self._expect("RBRACKET")
            return Comprehension(kind="list", element=first, generators=gens)
        elems = [first]
        while self._peek().kind == "COMMA":
            self._advance()
            if self._peek().kind == "RBRACKET": break
            elems.append(self._parse_expr(0))
        self._expect("RBRACKET")
        return ListExpr(elements=elems)

    def _parse_dict_or_set(self):
        self._expect("LBRACE")
        if self._peek().kind == "RBRACE":
            self._advance(); return DictExpr(pairs=[])
        first = self._parse_expr(0)
        # Check for struct initializer syntax: {field = value, ...}
        if self._peek().kind == "ASSIGN":
            # This is a struct initializer with named fields
            self._advance()  # skip =
            self._parse_expr(0)  # parse and discard field value
            # Skip any remaining fields
            while self._peek().kind == "COMMA":
                self._advance()
                if self._peek().kind == "RBRACE": break
                self._parse_expr(0)  # skip field name
                if self._peek().kind == "ASSIGN": self._advance()
                self._parse_expr(0)  # skip field value
            self._expect("RBRACE")
            # Return as dict for now (struct init not semantically tracked)
            return DictExpr(pairs=[])
        if self._peek().kind == "COLON":
            self._advance(); val = self._parse_expr(0)
            if self._is_kw("for"):
                gens = self._parse_generators()
                self._expect("RBRACE")
                return Comprehension(kind="dict", element=first, key=val, generators=gens)
            pairs = [(first, val)]
            while self._peek().kind == "COMMA":
                self._advance()
                if self._peek().kind == "RBRACE": break
                k = self._parse_expr(0); self._expect("COLON"); v = self._parse_expr(0)
                pairs.append((k, v))
            self._expect("RBRACE")
            return DictExpr(pairs=pairs)
        if self._is_kw("for"):
            gens = self._parse_generators()
            self._expect("RBRACE")
            return Comprehension(kind="set", element=first, generators=gens)
        # Handle named field if first element is followed by =
        if self._peek().kind == "ASSIGN":
            self._advance(); self._parse_expr(0)
            while self._peek().kind == "COMMA":
                self._advance()
                if self._peek().kind == "RBRACE": break
                self._parse_expr(0)  # field name or value
                if self._peek().kind == "ASSIGN": self._advance(); self._parse_expr(0)
            self._expect("RBRACE")
            return DictExpr(pairs=[])
        elems = [first]
        while self._peek().kind == "COMMA":
            self._advance()
            if self._peek().kind == "RBRACE": break
            e = self._parse_expr(0)
            # Handle named field (positional then named): {ctx, field = value}
            if self._peek().kind == "ASSIGN":
                self._advance(); self._parse_expr(0)
                while self._peek().kind == "COMMA":
                    self._advance()
                    if self._peek().kind == "RBRACE": break
                    self._parse_expr(0)
                    if self._peek().kind == "ASSIGN": self._advance(); self._parse_expr(0)
                break
            elems.append(e)
        self._expect("RBRACE")
        return SetExpr(elements=elems)

    def _parse_generator_target(self):
        t = self._peek()
        if t.kind == "LPAREN":
            self._advance()
            sub = self._parse_generator_target()
            self._expect("RPAREN")
            target = f"({sub})"
        elif t.kind == "LBRACKET":
            # List-pattern unpacking target: `for [off] in ...`
            self._advance()
            sub = self._parse_generator_target()
            self._expect("RBRACKET")
            target = f"[{sub}]"
        elif t.kind in ("NAME", "KW"):
            target = self._advance().value
        else:
            target = self._expect("NAME").value
        while self._peek().kind == "COMMA":
            self._advance()
            if self._is_kw("in"):
                break
            sub_t = self._peek()
            if sub_t.kind == "LPAREN":
                self._advance()
                inner = self._parse_generator_target()
                self._expect("RPAREN")
                target += f", ({inner})"
            elif sub_t.kind in ("NAME", "KW"):
                target += ", " + self._advance().value
            else:
                target += ", " + self._expect("NAME").value
        return target

    def _parse_generator(self):
        self._expect("KW", "for")
        target = self._parse_generator_target()
        self._expect("KW", "in")
        iterable = self._parse_expr(1)
        conditions = []
        while self._is_kw("if"):
            self._advance(); conditions.append(self._parse_expr(1))
        return Generator(target=target, iterable=iterable, conditions=conditions)

    def _parse_generators(self):
        """Parse one or more chained `for ... in ... [if ...]` clauses, as in
        nested comprehensions: {a*b for a in xs for b in ys}."""
        gens = [self._parse_generator()]
        while self._is_kw("for"):
            gens.append(self._parse_generator())
        return gens

    def _parse_struct_params_as_fields(self) -> list:
        """Parse struct parameter block [name: Type = default, ...] as VarDecl fields.
        Handles //, * separators and nested brackets in type annotations and defaults."""
        self._expect("LBRACKET")
        fields = []
        while True:
            t = self._peek()
            if t.kind in ('RBRACKET', 'EOF'):
                self._advance()
                break
            # Skip positional-only (//) and keyword-only (*) separators
            if t.kind == 'OP' and t.value in ('//', '*'):
                self._advance()
                if self._peek().kind == 'COMMA':
                    self._advance()
                continue
            if t.kind == 'COMMA':
                self._advance()
                continue
            # Try to parse: name: Type [= default]
            if t.kind == 'NAME':
                name = t.value
                self._advance()
                if self._peek().kind == 'COLON':
                    self._advance()  # consume ':'
                    type_ann = self._parse_type_ann()
                    # Skip optional default value ('=' tokenizes as ASSIGN)
                    if self._peek().kind in ('EQUAL', 'ASSIGN') or (
                            self._peek().kind == 'OP' and self._peek().value == '='):
                        self._advance()  # consume '='
                        # Skip default value expression (balanced brackets)
                        depth = 0
                        while True:
                            pk = self._peek()
                            if pk.kind == 'EOF':
                                break
                            if pk.kind in ('LPAREN', 'LBRACKET', 'LBRACE'):
                                depth += 1
                                self._advance()
                            elif pk.kind in ('RPAREN', 'RBRACE'):
                                depth -= 1
                                self._advance()
                            elif pk.kind == 'RBRACKET':
                                if depth <= 0:
                                    break
                                depth -= 1
                                self._advance()
                            elif pk.kind == 'COMMA' and depth == 0:
                                break
                            else:
                                self._advance()
                    # `name: TraitName` is a generic TYPE parameter (T conforms
                    # to the trait), not a comptime VALUE parameter — it must
                    # NOT become a real field, or @fieldwise_init's synthesized
                    # constructor gets an extra phantom parameter (see
                    # __init__'s _known_traits comment).
                    bare_ann = type_ann.lstrip('*')
                    if bare_ann not in self._known_traits:
                        fields.append(VarDecl(name=name, type_ann=type_ann, value=None))
                else:
                    # No colon — skip this token (could be a bare type name)
                    pass
            else:
                self._advance()  # skip unexpected token
        return fields

    def _skip_bracketed(self):
        """Consume a balanced [...] block."""
        self._expect("LBRACKET")
        depth = 1
        while depth > 0:
            t = self._advance()
            if t.kind == "LBRACKET":
                depth += 1
            elif t.kind == "RBRACKET":
                depth -= 1
            elif t.kind == "EOF": break

    def _parse_generic_params_capture(self):
        """Consume a `def f[dtype: DType, width: SIMDSize, //, ...](...)`
        generic/comptime parameter block like `_skip_bracketed`, but also
        return just the parameter names in declaration order (ignoring
        types, trait bounds, defaults, and the `//` comptime/runtime
        separator) — enough for the interpreter to bind a call-site
        subscript (`f[Int32]()`) to names by position, e.g. so the function
        body can read `dtype` as a plain value."""
        self._expect("LBRACKET")
        names = []
        depth = 1
        expect_name = True
        while depth > 0:
            t = self._peek()
            if t.kind == "LBRACKET":
                self._advance(); depth += 1; continue
            if t.kind == "RBRACKET":
                self._advance(); depth -= 1; continue
            if t.kind == "EOF":
                break
            if t.kind == "COMMA" and depth == 1:
                self._advance(); expect_name = True; continue
            if depth == 1 and expect_name and t.kind in ("NAME", "KW"):
                names.append(t.value)
                self._advance()
                expect_name = False
                continue
            self._advance()
        return names

    def _skip_fn_quals(self):
        """Skip function-type qualifiers between a parameter list and `->`:
        capturing, raises, unified, register_passable, and calling-convention
        markers thin / abi("C"). Note `raises` lexes as a keyword, the rest as
        plain names, so accept both token kinds."""
        while self._peek().kind in ("NAME", "KW") and self._peek().value in (
            "capturing", "raises", "unified", "register_passable", "thin", "abi"):
            self._advance()
            # abi may take a parenthesized convention string: abi("C")
            if self._peek().kind == "LPAREN":
                self._advance()  # consume LPAREN
                depth = 1
                while depth > 0:
                    t = self._advance()
                    if t.kind == "LPAREN":
                        depth += 1
                    elif t.kind == "RPAREN":
                        depth -= 1
                    elif t.kind == "EOF": break

    def _parse_type_ann(self) -> str:
        """Parse a type annotation, including a trailing `?` optional-type suffix
        (`Token?` == `Optional[Token]`)."""
        name = self._parse_type_ann_inner()
        if self._peek().kind == "OP" and self._peek().value == "?":
            self._advance()
            name = f"Optional[{name}]"
        return name

    def _parse_type_ann_inner(self) -> str:
        """Parse a type annotation: Name or Name[TypeArgs] or Name.Member.Type[Args] or `backtick_type`."""
        # Handle * prefix for variadic/unpacking types (*Ts)
        prefix = ""
        if self._peek().kind == "OP" and self._peek().value == "*":
            prefix = "*"
            self._advance()
        # Handle `ref` or `mut` keyword prefix on type (lifetime annotation)
        if self._is_kw("ref") or self._is_kw("mut"):
            self._advance()  # drop ref/mut prefix
            # Skip lifetime parameters in brackets: ref[Origin]
            if self._peek().kind == "LBRACKET":
                self._skip_bracketed()
        # Handle backtick-quoted MLIR types (e.g., `!pop.scalar<bool>`)
        if self._peek().kind == "STRING" and self._peek().value.startswith("`"):
            return prefix + self._advance().value  # return the backtick string as-is
        # Forward-reference string annotation: `-> "TermState"`, `x: "SomeType"`
        # (PEP 484). Strip the quotes and treat the contents as the type name.
        if self._peek().kind == "STRING":
            return prefix + self._strip_string_prefix_and_quotes(self._advance().value)
        # Handle parenthesized types like () for unit type
        if self._peek().kind == "LPAREN":
            name = prefix + "("
            self._advance()
            depth = 1
            while depth > 0:
                t = self._advance()
                if t.kind == "LPAREN":
                    depth += 1
                    name += "("
                elif t.kind == "RPAREN":
                    depth -= 1
                    if depth > 0:
                        name += ")"
                elif t.kind == "EOF":
                    break
                else:
                    name += t.value
            name += ")"
            return name
        # Allow KW tokens as type names (e.g., "let", "var", "if")
        t = self._peek()
        if t.kind == "NAME": name = prefix + self._advance().value
        elif t.kind == "KW":
            kw_value = self._advance().value
            # Handle function types: def() -> ReturnType
            if kw_value == "def":
                # Skip function parameters in parentheses and brackets
                if self._peek().kind == "LBRACKET":
                    self._skip_bracketed()  # skip generic parameters [T, ...]
                if self._peek().kind == "LPAREN":
                    # Skip parameter list: consume balanced parentheses
                    self._advance()  # consume LPAREN
                    depth = 1
                    while depth > 0:
                        t = self._advance()
                        if t.kind == "LPAREN":
                            depth += 1
                        elif t.kind == "RPAREN":
                            depth -= 1
                        elif t.kind == "EOF": break
                # Skip optional qualifiers like 'capturing', 'raises', 'unified',
                # calling-convention markers 'thin'/'abi("C")', etc.
                # ('raises' lexes as a keyword, the rest as names.)
                while self._peek().kind in ("NAME", "KW") and self._peek().value in ("capturing", "raises", "unified", "register_passable", "thin", "abi"):
                    self._advance()
                    # capturing/abi may take a bracketed or parenthesized argument list
                    if self._peek().kind == "LBRACKET":
                        self._skip_bracketed()
                    if self._peek().kind == "LPAREN":
                        self._advance()  # consume LPAREN
                        depth = 1
                        while depth > 0:
                            t = self._advance()
                            if t.kind == "LPAREN":
                                depth += 1
                            elif t.kind == "RPAREN":
                                depth -= 1
                            elif t.kind == "EOF": break
                # Skip return type if present
                if self._peek().kind == "ARROW":
                    self._advance()  # skip ->
                    # Recursively parse the return type
                    return_type = self._parse_type_ann()
                    return prefix + f"def ... -> {return_type}"
                return prefix + "def"
            name = prefix + kw_value
        else: raise SyntaxError(f"{self._loc(t)}Expected NAME or KW got {t.kind}({t.value!r})")
        # Support dotted type names like __mlir_type.i1 or __mlir_type.`backtick_type`
        while self._peek().kind == "DOT":
            self._advance()  # consume dot
            # Next part can be a NAME (including KW like mut, ref) or a backtick-quoted type
            if self._peek().kind == "STRING" and self._peek().value.startswith("`"):
                name += "." + self._advance().value
            elif self._peek().kind in ("NAME", "KW"):
                name += "." + self._advance().value
            else:
                name += "." + self._expect("NAME").value  # error for invalid syntax
        # Handle function call types like type_of(x)
        if self._peek().kind == "LPAREN":
            self._advance()  # (
            name += "("
            depth = 1
            while depth > 0:
                t = self._advance()
                if t.kind == "LPAREN":
                    depth += 1
                    name += "("
                elif t.kind == "RPAREN":
                    depth -= 1
                    if depth > 0:
                        name += ")"
                elif t.kind == "EOF":
                    break
                else:
                    name += t.value
            name += ")"
            # Do NOT return here; check for dotted names and subscripts after the call
            # Second dotted-name loop after function call
            while self._peek().kind == "DOT":
                self._advance()  # consume dot
                # Next part can be a NAME or a backtick-quoted type
                if self._peek().kind == "STRING" and self._peek().value.startswith("`"):
                    name += "." + self._advance().value
                else:
                    name += "." + self._expect("NAME").value
        if self._peek().kind != "LBRACKET":
            # Handle PEP 604 union types: X | Y | Z  and trait intersections X & Y & Z
            while self._peek().kind == "OP" and self._peek().value in ("|", "&"):
                op = self._advance().value
                rhs = self._parse_type_ann()
                name = name + f" {op} " + rhs
            return name
        # Consume [TypeArgs] and any chained subscripts, .member accesses, or
        # comptime-call applications, e.g. `_field_types_of[Self.T]()[idx]`.
        parts = [name]
        while self._peek().kind in ("LBRACKET", "DOT", "LPAREN"):
            if self._peek().kind == "DOT":
                self._advance()  # consume dot
                if self._peek().kind == "STRING" and self._peek().value.startswith("`"):
                    parts.append("." + self._advance().value)
                elif self._peek().kind in ("NAME", "KW"):
                    parts.append("." + self._advance().value)
                else:
                    break
            elif self._peek().kind == "LPAREN":
                self._advance()  # (
                parts.append("(")
                depth = 1
                while depth > 0:
                    t = self._advance()
                    if t.kind == "LPAREN":
                        depth += 1
                        parts.append("(")
                    elif t.kind == "RPAREN":
                        depth -= 1
                        if depth > 0: parts.append(")")
                    elif t.kind == "EOF": break
                    else: parts.append(t.value)
                parts.append(")")
            else:
                self._advance()  # [
                parts.append("[")
                depth = 1
                while depth > 0:
                    t = self._advance()
                    if t.kind == "LBRACKET":
                        depth += 1
                        parts.append("[")
                    elif t.kind == "RBRACKET":
                        depth -= 1
                        if depth > 0: parts.append("]")
                    elif t.kind == "EOF": break
                    else: parts.append(t.value)
                parts.append("]")
        result = "".join(parts)
        # Handle PEP 604 union types: X | Y | Z  and trait intersections X & Y & Z
        while self._peek().kind == "OP" and self._peek().value in ("|", "&"):
            op = self._advance().value
            rhs = self._parse_type_ann()
            result = result + f" {op} " + rhs
        return result

# ── Code generator ─────────────────────────────────────────────────
def emit_module(stmts: list, indent: int = 0) -> str:
    return "\n".join(emit(s, indent) for s in stmts)

def emit(node, indent: int = 0) -> str:
    pad = "    " * indent
    if isinstance(node,IntLiteral): return str(node.value)
    if isinstance(node,FloatLiteral): return repr(node.value)
    if isinstance(node,BoolLiteral): return str(node.value)
    if isinstance(node,StringLiteral): return node.value
    if isinstance(node,EllipsisLiteral): return "..."
    if isinstance(node,IdentExpr): return node.name
    if isinstance(node,CallExpr):
        f = emit(node.func, 0) if not isinstance(node.func,str) else node.func
        args = ", ".join(emit(a, 0) for a in node.args)
        return f"{f}({args})"
    if isinstance(node,BinaryOp): return f"({emit(node.left, 0)} {node.op} {emit(node.right, 0)})"
    if isinstance(node,UnaryOp):  return f"({node.op} {emit(node.operand, 0)})"
    if isinstance(node,TernaryExpr): return f"({emit(node.then_val, 0)} if {emit(node.condition, 0)} else {emit(node.else_val, 0)})"
    if isinstance(node,WalrusExpr): return f"({node.name} := {emit(node.value, 0)})"
    if isinstance(node,MemberExpr): return f"{emit(node.obj, 0)}.{node.member}"
    if isinstance(node,SubscriptExpr):
        # A tuple index is multi-dimensional indexing (a[i, j], a[0:2, ::]); emit
        # the elements comma-joined without the tuple's surrounding parentheses.
        if isinstance(node.index, TupleExpr):
            inner = ", ".join(emit(e, 0) for e in node.index.elements)
            return f"{emit(node.obj, 0)}[{inner}]"
        return f"{emit(node.obj, 0)}[{emit(node.index, 0)}]"
    if isinstance(node,SliceExpr):
        start = emit(node.start, 0) if node.start is not None else ""
        stop  = emit(node.stop, 0)  if node.stop  is not None else ""
        step  = getattr(node, "step", None)
        body  = f"{start}:{stop}:{emit(step, 0)}" if step is not None else f"{start}:{stop}"
        # A bare slice (obj=None) is one element of a multi-dim index; emit just
        # the slice. Otherwise emit the indexing expression obj[...].
        if node.obj is None:
            return body
        return f"{emit(node.obj, 0)}[{body}]"
    if isinstance(node,ListExpr): return "[" + ", ".join(emit(e, 0) for e in node.elements) + "]"
    if isinstance(node,DictExpr): return "{" + ", ".join(f"{emit(k, 0)}: {emit(v, 0)}" for k,v in node.pairs) + "}"
    if isinstance(node,SetExpr): return "{" + ", ".join(emit(e, 0) for e in node.elements) + "}"
    if isinstance(node,TupleExpr):
        if not node.elements: return "()"
        return "(" + ", ".join(emit(e, 0) for e in node.elements) + ("," if len(node.elements)==1 else "") + ")"
    if isinstance(node,LambdaExpr):
        pstr = ", ".join(p[0] + (f"={emit(p[1])}" if p[1] is not None else "") for p in node.params)
        return f"lambda {pstr}: {emit(node.body)}"
    if isinstance(node,Comprehension):
        gens = " ".join(f"for {g.target} in {emit(g.iterable)}" + "".join(f" if {emit(c)}" for c in g.conditions) for g in node.generators)
        if node.kind == "list": return f"[{emit(node.element)} {gens}]"
        if node.kind == "set":  return "{" + f"{emit(node.element)} {gens}" + "}"
        if node.kind == "dict": return "{" + f"{emit(node.element)}: {emit(node.key)} {gens}" + "}"
        return f"({emit(node.element)} {gens})"
    if isinstance(node,ExprStmt): return f"{pad}{emit(node.value, 0)}"
    if isinstance(node,AssignStmt): return f"{pad}{emit(node.target)} = {emit(node.value, 0)}"
    if isinstance(node,AugAssignStmt): return f"{pad}{emit(node.target)} {node.op} {emit(node.value, 0)}"
    if isinstance(node,VarDecl):
        ann = f": {node.type_ann}" if node.type_ann else ""
        val = f" = {emit(node.value, 0)}" if node.value is not None else ""
        return f"{pad}{node.name}{ann}{val}"
    if isinstance(node,MultiAssignStmt):
        return f"{pad}" + " = ".join(emit(t) for t in node.targets) + " = " + emit(node.value, 0)
    if isinstance(node,ImportStmt):
        def _seg(m, a):
            return m + (f" as {a}" if a else "")
        parts = [_seg(node.module, node.alias)]
        for m, a in (node.extra or []):
            parts.append(_seg(m, a))
        return f"{pad}import " + ", ".join(parts)
    if isinstance(node,FromImportStmt):
        if node.wildcard: return f"{pad}from {node.module} import *"
        names = ", ".join(n + (f" as {a}" if a else "") for n,a in node.names)
        return f"{pad}from {node.module} import {names}"
    if isinstance(node,IfStmt):
        out = [f"{pad}if {emit(node.condition, 0)}:"]
        out += [emit(s,indent+1) for s in node.then_body]
        for (ec,eb) in node.elifs:
            out.append(f"{pad}elif {emit(ec)}:"); out += [emit(s,indent+1) for s in eb]
        if node.else_body is not None:
            out.append(f"{pad}else:"); out += [emit(s,indent+1) for s in node.else_body]
        return "\n".join(out)
    if isinstance(node,WhileStmt):
        out = [f"{pad}while {emit(node.condition, 0)}:"]
        out += [emit(s,indent+1) for s in node.body]
        if node.else_body is not None:
            out.append(f"{pad}else:"); out += [emit(s,indent+1) for s in node.else_body]
        return "\n".join(out)
    if isinstance(node,ForStmt):
        out = [f"{pad}for {emit(node.target) if not isinstance(node.target,str) else node.target} in {emit(node.iterable)}:"]
        out += [emit(s,indent+1) for s in node.body]
        if node.else_body is not None:
            out.append(f"{pad}else:"); out += [emit(s,indent+1) for s in node.else_body]
        return "\n".join(out)
    if isinstance(node,FunctionDef):
        def _fmt_param(n,t):
            ann = f": {t}" if t else ""
            return f"{n}{ann}"  # strip Mojo arg-convention prefix for Python
        params = ", ".join(_fmt_param(n,t) for n,t in node.params)
        ret = f" -> {node.return_type}" if node.return_type else ""
        out = [f"{pad}@{d}" for d in node.decorators]
        out.append(f"{pad}def {node.name}({params}){ret}:")
        out += [emit(s,indent+1) for s in node.body]
        return "\n".join(out)
    if isinstance(node,PassStmt): return f"{pad}pass"
    if isinstance(node,ReturnStmt):
        val = f" {emit(node.value, 0)}" if node.value is not None else ""
        return f"{pad}return{val}"
    if isinstance(node,RaiseStmt):
        val = f" {emit(node.value, 0)}" if node.value is not None else ""
        return f"{pad}raise{val}"
    if isinstance(node,BreakStmt): return f"{pad}break"
    if isinstance(node,ContinueStmt): return f"{pad}continue"
    if isinstance(node,AssertStmt):
        val = f" {emit(node.value, 0)}" if node.value is not None else ""
        msg_s = f", {emit(node.msg)}" if node.msg is not None else ""
        return f"{pad}assert{val}{msg_s}"
    if isinstance(node,TryStmt):
        out = [f"{pad}try:"]
        out += [emit(s,indent+1) for s in node.body]
        for h in node.handlers:
            if isinstance(h.exc_type, list):
                exc = " (" + ", ".join(h.exc_type) + ")"
            elif h.exc_type:
                exc = f" {h.exc_type}"
            else:
                exc = ""
            name = f" as {h.name}"  if h.name    else ""
            out.append(f"{pad}except{exc}{name}:")
            out += [emit(s,indent+1) for s in h.body]
        if node.else_body:
            out.append(f"{pad}else:"); out += [emit(s,indent+1) for s in node.else_body]
        if node.finally_body:
            out.append(f"{pad}finally:"); out += [emit(s,indent+1) for s in node.finally_body]
        return "\n".join(out)
    if isinstance(node,WithStmt):
        items_str = ", ".join(f"{emit(i.expr)} as {i.alias}" if i.alias else emit(i.expr) for i in node.items)
        out = [f"{pad}with {items_str}:"]
        out += [emit(s,indent+1) for s in node.body]
        return "\n".join(out)
    if isinstance(node,ComptimeIfStmt):
        out = [f"{pad}if {emit(node.condition, 0)}:  # comptime"]
        out += [emit(s,indent+1) for s in node.then_body]
        for (ec,eb) in node.elifs:
            out.append(f"{pad}elif {emit(ec)}:"); out += [emit(s,indent+1) for s in eb]
        if node.else_body is not None:
            out.append(f"{pad}else:"); out += [emit(s,indent+1) for s in node.else_body]
        return "\n".join(out)
    if isinstance(node,ComptimeForStmt):
        out = [f"{pad}for {node.target} in {emit(node.iterable)}:  # comptime"]
        out += [emit(s,indent+1) for s in node.body]
        return "\n".join(out)
    if isinstance(node,StructDef):
        _OWN_DECS = {"Copyable","Movable","ImplicitlyCopyable","ExplicitlyCopyable",
                     "Writable","Sized","Boolable","Stringable","Hashable","AnyType"}
        has_init = any(d == "fieldwise_init" for d in node.decorators)
        ext_decs = [d for d in node.decorators if d not in _OWN_DECS and d != "fieldwise_init"]
        out = [f"{pad}@{d}" for d in ext_decs]
        out.append(f"{pad}class {node.name}:")
        body = []
        if has_init and node.fields:
            ps = ", ".join(f.name for f in node.fields if isinstance(f, VarDecl))
            body.append(f"{pad}    def __init__(self, {ps}):")
            for f in node.fields:
                if isinstance(f, VarDecl):
                    body.append(f"{pad}        self.{f.name} = {f.name}")
                else:
                    body.append(f"{pad}        self.{emit(f.target)} = {emit(f.target)}")
        elif node.fields:
            for f in node.fields:
                if isinstance(f, VarDecl):
                    ann = f": {f.type_ann}" if f.type_ann else ""
                    val = f" = {emit(f.value)}" if f.value is not None else " = None"
                    body.append(f"{pad}    {f.name}{ann}{val}")
                else:
                    val = f" = {emit(f.value)}" if f.value is not None else " = None"
                    body.append(f"{pad}    {emit(f.target)}{val}")
        for m in node.methods:
            body.append(emit(m,indent+1))
        out += body if body else [f"{pad}    pass"]
        return "\n".join(out)
    if isinstance(node,TraitDef):
        out = [f"{pad}class {node.name}:  # trait"]
        body = []
        for m in node.methods:
            is_abs = (not m.body or
                      (len(m.body)==1 and isinstance(m.body[0],PassStmt)) or
                      (len(m.body)==1 and isinstance(m.body[0],ExprStmt)
                       and isinstance(m.body[0].value,EllipsisLiteral)))
            if is_abs: body.append(f"{pad}    @abstractmethod")
            body.append(emit(m,indent+1))
        out += body if body else [f"{pad}    pass"]
        return "\n".join(out)
    # Transfer sigil ^ is stripped by the tokenizer (XFER ignored)
    raise TypeError(f"Cannot emit {type(node).__name__}")

# ── Driver ──────────────────────────────────────────────────────────
def compile(src: str, filename: str = "") -> str:
    tokens = py_tokenize(src)
    stmts  = Parser(tokens).with_filename(filename).parse_module()
    return emit_module(stmts)

def compile_with_interpreter(src: str, filename: str = "") -> str:
    # Compile Mojo source to GIMPLE C using gimple_codegen.
    # This is the interpreter-based compilation path used during bootstrap.
    from gimple_codegen import compile_to_gimple
    return compile_to_gimple(src, do_imports=False, filename=filename)

if __name__ == '__main__':
    import sys
    filename = sys.argv[1] if len(sys.argv) >= 2 else "<stdin>"
    src = sys.stdin.read() if len(sys.argv) < 2 else open(filename).read()
    try:
        print(compile(src, filename=filename))
    except SyntaxError as e:
        print(str(e), file=sys.stderr)
        sys.exit(1)
