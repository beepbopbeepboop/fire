def _strip_inline_comment(s: str) -> str:
    """Remove trailing # comment, respecting quoted strings (including backtick strings and f/r/b prefixes)."""
    in_str = None
    i = 0
    while i < len(s):
        c = s[i]
        if in_str:
            if c == "\\" and in_str != '`': i += 2; continue
            if c == in_str: in_str = None
        elif c in ('"', "'", '`'):
            in_str = c
        elif i > 0 and c in ('"', "'") and s[i-1] in 'fFrRbBuUtT':
            # f"..." prefix: already entered via the quote char above
            in_str = c
        elif c == _CMT_CHAR:
            return s[:i]
        i += 1
    return s

def _split_on_separators(s: str) -> list[str]:
    """Split on ';' statement separator, respecting quoted strings (including backtick strings)."""
    parts, buf, in_str = [], [], None
    i = 0
    while i < len(s):
        c = s[i]
        if in_str:
            buf.append(c)
            if c == "\\" and in_str != '`' and i + 1 < len(s):
                i += 1; buf.append(s[i])
            elif c == in_str:
                in_str = None
        elif c in ('"', "'", '`'):
            in_str = c; buf.append(c)
        elif c == _SEP_CHAR:
            parts.append("".join(buf)); buf = []
        else:
            buf.append(c)
        i += 1
    parts.append("".join(buf))
    return parts

def py_tokenize(src: str) -> list[Token]:
    """Tokenize with layout rules derived from the .md spec:
        - Indentation (4 spaces) → INDENT/DEDENT
        - ';' → statement separator
        - '#' → end-of-line comment
        - Multi-line statements use indentation (no backslash continuation)"""
    import re
    string_cache = {}
    string_idx = [0]
    def replace_multiline_strings(src):
        def repl(m):
            placeholder = f"__MOJO_STR_{string_idx[0]}__"
            string_cache[placeholder] = m.group(0)
            string_idx[0] += 1
            # Preserve the original newline count: collapsing a multi-line
            # triple-quoted string (a docstring is the common case) to a
            # single-line placeholder shifted every subsequent physical line
            # number by (that string's line count - 1) — real bug, found via
            # `for` loops later in this exact file (mojo.py has a top-of-file
            # module docstring) reporting a diagnostic line number dozens of
            # lines before the loop's actual location, off by roughly the
            # cumulative length of every docstring/multi-line string above it.
            return placeholder + '\n' * m.group(0).count('\n')
        # Build patterns without literal triple-quotes in source (avoids bootstrap self-match)
        _dq = '"' * 3
        _sq = "'" * 3
        src = re.sub(r'[fFrRbBuU]{0,2}' + _dq + r'[\s\S]*?' + _dq, repl, src)
        src = re.sub(r'[fFrRbBuU]{0,2}' + _sq + r'[\s\S]*?' + _sq, repl, src)
        return src

    src = replace_multiline_strings(src)
    raw_lines = src.splitlines()
    # Join backslash-continued lines: "expr = \\\n    continuation" → one logical line
    joined = []
    line_nums = []  # track physical line number (1-based) for each logical line
    i = 0
    while i < len(raw_lines):
        start_line = i + 1  # 1-indexed physical line number
        line = raw_lines[i]
        while line.rstrip().endswith('\\'):
            line = line.rstrip()[:-1]  # strip the backslash
            i += 1
            if i < len(raw_lines):
                line = line + ' ' + raw_lines[i].lstrip()
            else:
                break
        joined.append(line)
        line_nums.append(start_line)
        i += 1
    # Phase 2: lex line by line
    out: list[Token] = []
    stack = [0]
    paren_depth = 0  # Track (), [], {} nesting to suppress INDENT/DEDENT inside
    for line_idx, line in enumerate(joined):
        physical_line = line_nums[line_idx]
        expanded = line.expandtabs(_INDENT_SIZE)
        raw_content = expanded.lstrip()
        if not raw_content or raw_content.startswith(_CMT_CHAR): continue
        content = _strip_inline_comment(raw_content).rstrip()
        if not content: continue
        indent = len(expanded) - len(raw_content)
        sub_stmts = _split_on_separators(content)
        for stmt_idx, stmt in enumerate(sub_stmts):
            stmt = stmt.strip()
            if not stmt: continue
            # Only emit INDENT/DEDENT when at paren depth 0
            if stmt_idx == 0 and paren_depth == 0:
                if indent > stack[-1]:
                    stack.append(indent)
                    out.append(Token("INDENT", "", line=physical_line, col=0))
                else:
                    while indent < stack[-1]:
                        stack.pop()
                        out.append(Token("DEDENT", "", line=physical_line, col=0))
            # Handle t-strings with nested braces before tokenization
            stmt_final = _process_nested_tstrings(stmt, string_cache, string_idx)

            for m in _TOKEN_RE.finditer(stmt_final):
                kind = m.lastgroup or "INT"
                val  = m.group()
                col  = m.start()
                if kind in ("WS", "UNK", "XFER"): continue
                if kind == "NAME" and val in _KEYWORDS: kind = "KW"
                # Restore multi-line strings from cache
                if kind == "NAME" and val in string_cache:
                    val = string_cache[val]
                    kind = "STRING"
                # Track paren/bracket/brace depth to suppress INDENT/NEWLINE inside
                if kind in ("LPAREN", "LBRACKET", "LBRACE") or val in ("(", "[", "{"): paren_depth += 1
                elif kind in ("RPAREN", "RBRACKET", "RBRACE") or val in (")", "]", "}"): paren_depth = max(0, paren_depth - 1)
                out.append(Token(kind, val, line=physical_line, col=col))
            # Only emit NEWLINE when paren depth is 0 (not inside brackets/parens)
            if paren_depth == 0:
                out.append(Token("NEWLINE", "", line=physical_line, col=0))
    last_line = 0
    if line_nums:
        last_line = line_nums[-1]
    while len(stack) > 1:
        stack.pop()
        out.append(Token("DEDENT", "", line=last_line, col=0))
    out.append(Token("EOF", "", line=last_line, col=0))
    return out

