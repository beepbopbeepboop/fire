def main() :
    print([[1], [2]] == [[1], [2]])
    print([[1], [2]] == [[1], [3]])
    print([{"a": 1}] == [{"a": 1}])
    print([{"a": 1}] == [{"a": 2}])
    print({"k": [1, 2]} == {"k": [1, 2]})
    print({"k": [1, 2]} == {"k": [1, 3]})
    print([[1, 2], [3]] == [[1, 2], [3]])
    print([[[1]]] == [[[1]]])
    print([[1]] == [[1, 1]])
    return 0

main()
