#!/usr/bin/env python3
"""Generate mojo/middle/rt_sigs.py: the C signature of every function the
runtime headers declare.

    python3 tools/gen_rt_sigs.py            # rewrite mojo/middle/rt_sigs.py
    python3 tools/gen_rt_sigs.py --check    # exit 1 if the file is stale

The headers are the single source of truth.  `GimpleGen._KNOWN_SIGS` is a
hand-written table of 606 of these; the headers declare about 1,070.  A call
to one of the other ~460 used to get no argument coercion at all (see
doc/GIR.md, "the call-argument hole").

The generated table is `name -> [ret, param0, param1, ...]`, C spellings, with
a trailing '...' for a variadic function.  A list, not a tuple, on purpose: a
tuple's slots are erased to int64_t when the compiler compiles itself.
"""
from __future__ import annotations

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from mojo.ir import reader                  # noqa: E402
from mojo.ir.instr import Module            # noqa: E402

# The headers every emitted module includes (module_gen.py's prelude).
HEADERS = ['fire_runtime.h', 'fire_sqlite3.h', 'fire_zlib.h', 'fire_ssl.h',
           'fire_ncurses.h']
OUT = os.path.join(ROOT, 'mojo', 'middle', 'rt_sigs.py')

_HEAD = '''"""GENERATED by tools/gen_rt_sigs.py from runtime/*.h -- do not edit.

`RT_SIGS[name]` is `[ret, param0, param1, ...]` in C spelling; a trailing
'...' marks a variadic function.  Regenerate after changing a runtime header:

    python3 tools/gen_rt_sigs.py
"""

RT_SIGS: dict[str, list[str]] = {
'''


def render() -> str:
    mod = Module('<runtime>')
    pre = reader.Reader(mod, [])
    pre.header_mode = True
    pre.lex(reader._LIBC, '<libc>')
    pre.parse_toplevel()
    rd = reader.Reader(mod, [os.path.join(ROOT, 'runtime')])
    rd.typedefs = pre.typedefs
    rd.header_mode = True
    for h in HEADERS:
        rd.include(h)
    lines = [_HEAD]
    for name in sorted(mod.sigs):
        sig = mod.sigs[name]
        if sig.unchecked:
            continue
        row = [sig.ret.name] + [p.name for p in sig.params]
        if sig.variadic:
            row.append('...')
        lines.append('    %r: [%s],\n' % (name, ', '.join(repr(x) for x in row)))
    lines.append('}\n')
    return ''.join(lines)


def main() -> int:
    text = render()
    if '--check' in sys.argv[1:]:
        try:
            with open(OUT, encoding='utf-8') as f:
                cur = f.read()
        except OSError:
            cur = ''
        if cur != text:
            print('mojo/middle/rt_sigs.py is stale: run `python3 tools/gen_rt_sigs.py`')
            return 1
        print('mojo/middle/rt_sigs.py is current')
        return 0
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(text)
    print(f'wrote {os.path.relpath(OUT, ROOT)} ({text.count(chr(10)) - 9} signatures)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
