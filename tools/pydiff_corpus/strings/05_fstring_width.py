def main():
    print(f"[{7:5d}]")
    print(f"[{-7:5d}]")
    print(f"[{12345:3d}]")
    print(f"[{0:5d}]")
    print(f"[{'ab':5}]")
    print(f"[{'abcdefgh':3}]")
    width = 6
    print(f"[{42:{width}d}]")
    print(f"[{1.5:8}]")
    print(f"[{-2:4}]")
    print(f"[{'':4}]")
    print(f"[{10:2}]")
    print(f"[{9:{width - 4}}]")


main()
