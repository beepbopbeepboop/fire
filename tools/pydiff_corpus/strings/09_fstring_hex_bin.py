def main():
    print(f"{255:x}")
    print(f"{255:X}")
    print(f"{255:#x}")
    print(f"{0:x}")
    print(f"{-255:x}")
    print(f"{10:b}")
    print(f"{5:08b}")
    print(f"{8:o}")
    print(f"{255:#010x}")
    print(f"{-1:b}")
    print(f"{format(26, 'x')}")
    print(hex(255))
    print(bin(-5))
    print(oct(64))
    print(hex(0))


main()
