#!/usr/bin/env python3
"""The index of `bugs/plan/step-*.md`, generated from the step files themselves.

    python3 tools/plan_index.py            # print the table
    python3 tools/plan_index.py --write    # rewrite the block in doc/finish-formal.md
    python3 tools/plan_index.py --check    # exit 1 if the block is stale or the plan is malformed

The step files are the single source of the plan (`doc/finish-formal.md`
"Detailed steps"); this table is derived from each file's title line and its
`Class: ... Size: ... Depends: ... Blocks: ...` header line, so it cannot drift
from them. `--check` also fails on: a step missing the header line, a Class
outside easy/mid/hard, a Depends id that names no step file (a bare `NN`
matches any split `NNa`, `NNb`, ...), and a dependency cycle.
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PLAN = os.path.join(ROOT, "bugs", "plan")
DOC = os.path.join(ROOT, "doc", "finish-formal.md")
BEGIN = "<!-- BEGIN generated by tools/plan_index.py -->"
END = "<!-- END generated by tools/plan_index.py -->"
CLASSES = ("easy", "mid", "hard")


def load():
    steps = {}
    problems = []
    for path in sorted(glob.glob(os.path.join(PLAN, "step-*.md"))):
        name = os.path.basename(path)
        m = re.match(r"step-(\d{2}[a-z]?)-", name)
        if not m:
            problems.append(f"{name}: filename is not step-NN[x]-slug.md")
            continue
        sid = m.group(1)
        text = open(path).read().splitlines()
        title = re.sub(r"^#\s*plan/step-\S+?:\s*", "", text[0]) if text else ""
        hdr = next((l for l in text[:6] if l.startswith("Class:")), None)
        if hdr is None:
            problems.append(f"{name}: no 'Class: ... Size: ... Depends: ... Blocks: ...' line in the first 6 lines")
            continue
        fields = dict(re.findall(r"(Class|Size|Depends|Blocks):\s*(.*?)(?=\s{2,}(?:Class|Size|Depends|Blocks):|$)", hdr))
        cls = fields.get("Class", "").strip()
        if cls not in CLASSES:
            problems.append(f"{name}: Class '{cls}' is not one of {CLASSES}")
        steps[sid] = dict(file=name, title=title, cls=cls, size=fields.get("Size", "").strip(),
                          dep=fields.get("Depends", "").strip(), blocks=fields.get("Blocks", "").strip())
    return steps, problems


def dep_ids(field):
    if field.lower().startswith("none"):
        return []
    return re.findall(r"\b(\d{2}[a-z]?)\b", field)


def resolve(ids, steps):
    out, bad = set(), []
    for i in ids:
        hit = [s for s in steps if s == i or (len(i) == 2 and s.startswith(i))]
        if hit:
            out.update(hit)
        else:
            bad.append(i)
    return out, bad


def check(steps, problems):
    graph = {}
    for sid, s in steps.items():
        ds, bad = resolve(dep_ids(s["dep"]), steps)
        for b in bad:
            problems.append(f"{s['file']}: Depends names '{b}', which is no step file")
        graph[sid] = ds - {sid}
    state = {}

    def visit(n, path):
        if state.get(n) == 1:
            problems.append("dependency cycle: " + " -> ".join(path + [n]))
            return
        if state.get(n) == 2:
            return
        state[n] = 1
        for d in sorted(graph.get(n, ())):
            visit(d, path + [n])
        state[n] = 2

    for n in sorted(graph):
        visit(n, [])
    return problems


def table(steps):
    rows = ["| step | class | size | depends | title |", "|---|---|---|---|---|"]
    for sid in sorted(steps):
        s = steps[sid]
        dep = re.sub(r"\s*\(.*?\)", "", s["dep"]).strip()
        rows.append(f"| [`{sid}`](../bugs/plan/{s['file']}) | {s['cls']} | {s['size']} | {dep} | {s['title']} |")
    n = {c: sum(1 for s in steps.values() if s["cls"] == c) for c in CLASSES}
    rows.append("")
    rows.append(f"**{len(steps)} step files:** {n['easy']} easy, {n['mid']} mid, {n['hard']} hard. "
                "(Generated by `python3 tools/plan_index.py --write`; do not edit by hand.)")
    return "\n".join(rows)


def block(steps):
    return f"{BEGIN}\n\n{table(steps)}\n\n{END}"


def main(argv):
    steps, problems = load()
    problems = check(steps, problems)
    doc = open(DOC).read() if os.path.exists(DOC) else ""
    cur = block(steps)
    if "--write" in argv:
        if BEGIN in doc and END in doc:
            a, b = doc.index(BEGIN), doc.index(END) + len(END)
            open(DOC, "w").write(doc[:a] + cur + doc[b:])
        else:
            print("no generated block markers in", DOC, file=sys.stderr)
            return 1
    elif "--check" in argv:
        if BEGIN not in doc or END not in doc:
            problems.append("doc/finish-formal.md has no generated block")
        elif doc[doc.index(BEGIN):doc.index(END) + len(END)] != cur:
            problems.append("the index block in doc/finish-formal.md is stale: run --write")
    else:
        print(table(steps))
    for p in problems:
        print("PROBLEM:", p, file=sys.stderr)
    if "--check" in argv and not problems:
        print(f"PASS  plan index: {len(steps)} steps, no problems")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
